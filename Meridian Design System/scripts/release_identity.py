#!/usr/bin/env python3
"""Meridian — release identity + census renderer (stdlib only, offline).

Every human-readable version statement and every typed count in this package is generated here,
from three machine-readable sources and nothing else:

  release.json          version, channel, last stable, QA report and what it defers
  _ds_manifest.json     the census — exports, modules, cards, templates, tokens, themes, fonts
  api/families.json     the public family assignment and the maturity register

It rewrites the marked blocks in readme.md and docs/METRICS.md. This exists because the tree
called itself production-ready 3.5.0 in one file, a 4.2.0 tree in another, and carried unreleased
4.1/4.2 work in a third — and because a family table that summed to 284 sat under a sentence
claiming it covered 303.

  python scripts/release_identity.py            # print both blocks
  python scripts/release_identity.py --write     # rewrite readme.md + docs/METRICS.md
  python scripts/release_identity.py --check     # exit 1 on drift (CI gate)
"""
import collections, hashlib, json, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = {
    "readme.md": "release:generated",
    "docs/METRICS.md": "census:generated",
}
CHANNEL_LABEL = {
    "stable": "Production-ready",
    "rc": "Release candidate",
    "beta": "Beta",
    "development": "Development snapshot",
}
DOMAIN_ORDER = ["core", "data", "charts", "accounting", "trading", "operations", "shell", "decision"]

def load():
    release = json.loads((ROOT / "release.json").read_text(encoding="utf-8"))
    manifest = json.loads((ROOT / "_ds_manifest.json").read_text(encoding="utf-8"))
    families_path = ROOT / "api" / "families.json"
    families = json.loads(families_path.read_text(encoding="utf-8")) if families_path.exists() else None
    return release, manifest, families

def census(manifest):
    modules, domains = set(), collections.Counter()
    for comp in manifest["components"]:
        m = re.match(r"components/(\w+)/([\w.]+)\.(?:jsx|tsx|js)$", comp.get("sourcePath", ""))
        if not m:
            continue
        modules.add((m.group(1), m.group(2)))
        domains[m.group(1)] += 1
    return {
        "exports": len(manifest["components"]),
        "modules": len(modules),
        "domains": len({d for d, _ in modules}),
        "cards": len(manifest.get("cards", [])),
        "templates": len(manifest.get("templates", [])),
        "tokens": len(manifest.get("tokens", [])),
        "themes": len(manifest.get("themes", [])),
        "byDomain": domains,
    }

def manifest_hash():
    """Reported by the CLI only. Deliberately NOT rendered into the docs: a hash in prose is stale
    the moment the compiler runs, and a stale hash is worse than none."""
    return hashlib.sha256((ROOT / "_ds_manifest.json").read_bytes()).hexdigest()[:16]

def render_readme(release, manifest, families, c):
    label = CHANNEL_LABEL.get(release["channel"], release["channel"])
    consume = (f"Consumers should build against the last stable tag, **{release['lastStable']}**"
               if release["channel"] == "development" else
               f"This is the supported build (**{release['version']}**)")
    rc = (families or {}).get("totals", {}).get("releaseCandidate", 0)
    return "\n".join([
        f"**{label} · {release['version']} · last stable {release['lastStable']} · {release['declaredAt']}**",
        "",
        f"> {consume}; this tree is the working branch. Identity is declared once in `release.json` and "
        f"rendered from it by `scripts/release_identity.py` — no version is typed by hand anywhere in this "
        f"package. QA evidence: `{release['qaReport']}`"
        + (f", which still defers {len(release['qaDefers'])} item(s) "
           f"({'; '.join(release['qaDefers'])}) — that is why this is not " + ("stable" if release["channel"] == "rc" else "a release candidate") + "."
           if release.get("qaDefers") else "."),
        "",
        f"> **Census** (generated from `_ds_manifest.json`): "
        f"**{c['exports']} exports across {c['modules']} modules** in {c['domains']} domains · "
        f"{c['cards']} specimen cards · {c['templates']} templates · {c['tokens']} tokens · "
        f"{c['themes']} themes"
        + (f" · {rc} export(s) at release-candidate maturity (`api/families.json`)" if rc else "")
        + ".",
    ])

def render_metrics(release, manifest, families, c):
    lines = [
        f"Identity and every count below are generated by `scripts/release_identity.py` from "
        f"`release.json`, `_ds_manifest.json` and `api/families.json`. Do not hand-edit — a "
        f"hand-maintained count is how 284/118 outlived two releases.",
        "",
        f"**{CHANNEL_LABEL.get(release['channel'], release['channel'])} · {release['version']}** "
        f"(last stable {release['lastStable']}, declared {release['declaredAt']}) · namespace "
        f"`{manifest.get('namespace')}`",
        "",
        f"**{c['exports']} exports across {c['modules']} modules** · **{c['cards']} cards** · "
        f"**{c['templates']} templates** · **{c['tokens']} tokens** · **{c['themes']} themes**",
        "",
        "## Public families",
        "",
        "| Family | Exports | Release-candidate |",
        "|---|---:|---:|",
    ]
    if families:
        rc = collections.Counter(r["family"] for r in families["exports"] if r["stability"] == "release-candidate")
        for fam in sorted(families["counts"]):
            lines.append(f"| `{fam}` | {families['counts'][fam]} | {rc.get(fam, 0) or '—'} |")
        total = sum(families["counts"].values())
        lines.append(f"| **total** | **{total}** | **{families['totals']['releaseCandidate'] or '—'}** |")
        lines += ["", f"The {len(families['counts'])} families cover **all {total} exports** — "
                      f"`api/families.json` is generated by `scripts/generate_families.py`, which fails the "
                      f"release gate on an unclassified export, a phantom name, or a symbol claimed by two "
                      f"families. `legacy.js` re-exports the flat namespace so nothing in the 3.x line is "
                      f"forced to migrate."]
    lines += ["", "## Source layout", "", "| Folder | Exports |", "|---|---:|"]
    for domain in DOMAIN_ORDER:
        if c["byDomain"].get(domain):
            lines.append(f"| `components/{domain}` | {c['byDomain'][domain]} |")
    lines += ["", "Folder counts are an implementation detail. The family table above is the public "
                  "contract; `core` is precisely why the split exists."]
    return "\n".join(lines)

def splice(path, marker, block):
    text = (ROOT / path).read_text(encoding="utf-8")
    begin, end = f"<!-- {marker}:begin -->", f"<!-- {marker}:end -->"
    if begin not in text or end not in text:
        return None, f"{path}: {marker} markers missing"
    pre, rest = text.split(begin, 1)
    _, post = rest.split(end, 1)
    return pre + begin + "\n" + block + "\n" + end + post, None

def main():
    release, manifest, families = load()
    c = census(manifest)
    blocks = {
        "readme.md": render_readme(release, manifest, families, c),
        "docs/METRICS.md": render_metrics(release, manifest, families, c),
    }
    if families and families["totals"]["exports"] != c["exports"]:
        print(f"FAIL: api/families.json covers {families['totals']['exports']} exports, manifest has "
              f"{c['exports']} — run scripts/generate_families.py --write", file=sys.stderr)
        if "--check" in sys.argv:
            return 1

    drift, errors = [], []
    for path, marker in TARGETS.items():
        updated, err = splice(path, marker, blocks[path])
        if err:
            errors.append(err)
            continue
        current = (ROOT / path).read_text(encoding="utf-8")
        if "--write" in sys.argv:
            if updated != current:
                (ROOT / path).write_text(updated, encoding="utf-8")
                print(f"{path}: identity + census updated")
        elif updated != current:
            drift.append(path)

    for e in errors:
        print("FAIL: " + e, file=sys.stderr)
    if "--write" in sys.argv:
        return 1 if errors else 0
    if "--check" in sys.argv:
        if drift:
            print("DRIFT: " + ", ".join(drift) + " — run with --write", file=sys.stderr)
        if drift or errors:
            return 1
        print(f"release identity in sync · {release['version']} ({release['channel']}) · {c['exports']} exports · manifest {manifest_hash()}")
        return 0
    for path in TARGETS:
        print(f"--- {path} ---\n{blocks[path]}\n")
    return 1 if errors else 0

if __name__ == "__main__":
    sys.exit(main())
