#!/usr/bin/env python3
"""Meridian — card catalog sync (restored 3.5, stdlib only, offline).

The Design System tab renders every `@dsCard`-tagged .html verbatim; this script generates the
one flat index of that gallery so it is never hand-maintained:

  python scripts/sync_catalog.py            # print the index
  python scripts/sync_catalog.py --write    # (re)write guidelines/CARD_INDEX.md
  python scripts/sync_catalog.py --check    # exit 1 on drift
"""
import re, sys, pathlib, collections

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "guidelines" / "CARD_INDEX.md"
MARK = re.compile(r"<!--\s*@dsCard\s+([^>]*?)-->", re.S)
ATTR = re.compile(r'(\w+)="([^"]*)"')

def collect():
    cards = []
    for path in sorted(ROOT.rglob("*.card.html")) + sorted(ROOT.rglob("*.html")):
        if path.name.endswith(".dc.html") or "_ds" in path.name or path in [c[3] for c in cards]:
            continue
        try:
            head = path.read_text(encoding="utf-8", errors="ignore")[:600]
        except OSError:
            continue
        m = MARK.search(head)
        if not m:
            continue
        attrs = dict(ATTR.findall(m.group(1)))
        cards.append((attrs.get("group", "Ungrouped"), attrs.get("name", path.stem), attrs.get("subtitle", ""), path))
    # de-dup (rglob overlap)
    seen, out = set(), []
    for c in cards:
        if c[3] in seen:
            continue
        seen.add(c[3]); out.append(c)
    return out

def render(cards):
    groups = collections.OrderedDict()
    for g, n, s, p in sorted(cards, key=lambda c: (c[0], c[1])):
        groups.setdefault(g, []).append((n, s, p))
    lines = ["# Design System card index", "",
             f"GENERATED by `scripts/sync_catalog.py` — {len(cards)} cards. Do not hand-edit.", ""]
    for g, items in groups.items():
        lines.append(f"## {g} ({len(items)})")
        lines.append("")
        for n, s, p in items:
            rel = p.relative_to(ROOT).as_posix()
            lines.append(f"- **{n}** — `{rel}`" + (f" · {s}" if s else ""))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"

def main():
    text = render(collect())
    if "--write" in sys.argv:
        OUT.write_text(text, encoding="utf-8"); print(f"wrote {OUT.relative_to(ROOT)}"); return 0
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("DRIFT: guidelines/CARD_INDEX.md — run with --write", file=sys.stderr); return 1
        print("card index in sync"); return 0
    print(text); return 0

if __name__ == "__main__":
    sys.exit(main())
