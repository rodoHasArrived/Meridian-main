#!/usr/bin/env python3
"""Preview-first deterministic repository edit tool for Meridian."""

from __future__ import annotations

import argparse
import dataclasses
import datetime as dt
import fnmatch
import hashlib
import json
import os
import re
import sys
from pathlib import Path
from typing import Any

SCHEMA_VERSION = "1.0"
TOOL_VERSION = "0.1.0"
DEFAULT_EXCLUDES = (
    ".git/**",
    "**/.git/**",
    "bin/**",
    "**/bin/**",
    "obj/**",
    "**/obj/**",
    "node_modules/**",
    "**/node_modules/**",
    "archive/**",
    "**/archive/**",
    "artifacts/**",
    "**/artifacts/**",
    "docs/generated/**",
    "docs/ai/generated/**",
    "docs/source/generated/**",
    "src/**/wwwroot/workstation/assets/**",
)
GENERATED_MARKERS = (
    "<auto-generated",
    "@generated",
    "generated by",
    "do not edit",
)
TEXT_SUFFIXES = {
    ".cs",
    ".csproj",
    ".props",
    ".targets",
    ".fs",
    ".fsproj",
    ".ts",
    ".tsx",
    ".js",
    ".jsx",
    ".py",
    ".md",
    ".json",
    ".yml",
    ".yaml",
    ".xml",
    ".xaml",
    ".txt",
    ".ps1",
    ".sh",
    ".css",
    ".html",
}
IDENTIFIER_SUFFIXES = {".cs", ".ts", ".tsx", ".py"}


class EditToolError(Exception):
    """Raised for invalid recipes, unsafe paths, or drift."""


@dataclasses.dataclass(frozen=True)
class PlannedEdit:
    start: int
    end: int
    before: str
    after: str
    line_start: int
    line_end: int

    def to_json(self) -> dict[str, Any]:
        return {
            "start": self.start,
            "end": self.end,
            "lineStart": self.line_start,
            "lineEnd": self.line_end,
            "before": self.before,
            "after": self.after,
        }


def repo_root(start: Path | None = None) -> Path:
    current = (start or Path.cwd()).resolve()
    for candidate in (current, *current.parents):
        if (candidate / "Meridian.sln").is_file():
            return candidate
    raise EditToolError("Cannot locate Meridian.sln from current directory.")


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def load_json_value(raw: str | None, file_path: str | None, label: str) -> dict[str, Any]:
    if bool(raw) == bool(file_path):
        raise EditToolError(f"Provide exactly one of --{label}-json or --{label}-file.")
    try:
        if raw:
            value = json.loads(raw)
        else:
            value = json.loads(Path(file_path or "").read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise EditToolError(f"Invalid {label} JSON: {exc}") from exc
    if not isinstance(value, dict):
        raise EditToolError(f"{label} must be a JSON object.")
    return value


def rel_path(root: Path, path: Path) -> str:
    return path.resolve().relative_to(root).as_posix()


def is_within(root: Path, path: Path) -> bool:
    try:
        path.resolve().relative_to(root)
        return True
    except ValueError:
        return False


def matches_any(path: str, patterns: list[str] | tuple[str, ...]) -> bool:
    for pattern in patterns:
        if fnmatch.fnmatch(path, pattern):
            return True
        if "/**/" in pattern and fnmatch.fnmatch(path, pattern.replace("/**/", "/")):
            return True
    return False


def is_generated_path(path: str) -> bool:
    parts = set(path.split("/"))
    return "generated" in parts or path.endswith(".g.cs")


def is_archive_path(path: str) -> bool:
    return path.startswith("archive/") or "/archive/" in f"/{path}/"


def is_default_unsafe_path(path: str) -> bool:
    parts = set(path.split("/"))
    return (
        matches_any(path, DEFAULT_EXCLUDES)
        or bool(parts.intersection({"bin", "obj", "node_modules", "artifacts"}))
        or is_archive_path(path)
        or is_generated_path(path)
    )


def validate_recipe(recipe: dict[str, Any]) -> None:
    kind = recipe.get("kind")
    if kind not in {
        "literal_replace",
        "regex_replace",
        "anchored_block_replace",
        "identifier_text_rename",
    }:
        raise EditToolError("recipe.kind is required and must be a supported edit kind.")
    for required in ("include", "exclude", "maxFiles", "maxEdits"):
        if required not in recipe:
            raise EditToolError(f"recipe.{required} is required.")
    if not isinstance(recipe["include"], list) or not recipe["include"]:
        raise EditToolError("recipe.include must be a non-empty list of globs.")
    if not isinstance(recipe["exclude"], list):
        raise EditToolError("recipe.exclude must be a list of globs.")
    if int(recipe["maxFiles"]) < 1 or int(recipe["maxEdits"]) < 1:
        raise EditToolError("recipe.maxFiles and recipe.maxEdits must be positive.")
    if kind in {"literal_replace", "regex_replace", "identifier_text_rename"}:
        if not recipe.get("find"):
            raise EditToolError("recipe.find is required.")
        if "replace" not in recipe:
            raise EditToolError("recipe.replace is required.")
    if kind == "anchored_block_replace":
        if not recipe.get("startAnchor") or not recipe.get("endAnchor"):
            raise EditToolError("anchored_block_replace requires startAnchor and endAnchor.")
        if "replace" not in recipe:
            raise EditToolError("anchored_block_replace requires replace.")
    if kind == "regex_replace":
        re.compile(str(recipe["find"]))


def validate_scope(root: Path, scope: dict[str, Any], recipe: dict[str, Any]) -> list[Path]:
    raw_paths = scope.get("paths")
    if not isinstance(raw_paths, list) or not raw_paths:
        raise EditToolError("scope.paths must be a non-empty list.")
    allow_generated = bool(recipe.get("allowGenerated"))
    allow_archive = bool(recipe.get("allowArchive"))
    allowed: list[Path] = []
    for raw in raw_paths:
        candidate = (root / str(raw)).resolve()
        if not is_within(root, candidate):
            raise EditToolError(f"Scope path is outside repo root: {raw}")
        relative = rel_path(root, candidate)
        if is_default_unsafe_path(relative):
            if is_archive_path(relative) and allow_archive:
                pass
            elif is_generated_path(relative) and allow_generated:
                pass
            else:
                raise EditToolError(f"Scope path is unsafe by default: {relative}")
        if candidate.exists():
            allowed.append(candidate)
        else:
            raise EditToolError(f"Scope path does not exist: {relative}")
    return allowed


def iter_candidate_files(root: Path, scope_paths: list[Path], recipe: dict[str, Any]) -> list[Path]:
    include = [str(item) for item in recipe["include"]]
    exclude = [str(item) for item in recipe["exclude"]]
    allow_generated = bool(recipe.get("allowGenerated"))
    allow_archive = bool(recipe.get("allowArchive"))
    candidates: list[Path] = []
    for scope_path in scope_paths:
        paths = [scope_path] if scope_path.is_file() else [p for p in scope_path.rglob("*") if p.is_file()]
        for path in paths:
            relative = rel_path(root, path)
            if path.suffix.lower() not in TEXT_SUFFIXES:
                continue
            if not matches_any(relative, include):
                continue
            if matches_any(relative, exclude):
                continue
            if is_default_unsafe_path(relative):
                archive_path = is_archive_path(relative)
                generated_path = is_generated_path(relative)
                if archive_path and not allow_archive:
                    continue
                if generated_path and not allow_generated:
                    continue
                if not archive_path and not generated_path:
                    continue
            candidates.append(path)
    return sorted(dict.fromkeys(candidates), key=lambda p: rel_path(root, p))


def read_text(path: Path) -> str | None:
    try:
        raw = path.read_bytes()
        if b"\x00" in raw:
            return None
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        return None


def line_number(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def plan_literal(text: str, recipe: dict[str, Any]) -> list[PlannedEdit]:
    find = str(recipe["find"])
    replace = str(recipe["replace"])
    edits: list[PlannedEdit] = []
    start = 0
    while True:
        index = text.find(find, start)
        if index < 0:
            break
        edits.append(make_edit(text, index, index + len(find), replace))
        start = index + len(find)
    return edits


def plan_regex(text: str, recipe: dict[str, Any]) -> list[PlannedEdit]:
    pattern = re.compile(str(recipe["find"]))
    edits: list[PlannedEdit] = []
    for match in pattern.finditer(text):
        edits.append(make_edit(text, match.start(), match.end(), match.expand(str(recipe["replace"]))))
    return edits


def plan_identifier(text: str, path: Path, recipe: dict[str, Any]) -> list[PlannedEdit]:
    if path.suffix.lower() not in IDENTIFIER_SUFFIXES:
        return []
    identifier = str(recipe["find"])
    if not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", identifier):
        raise EditToolError("identifier_text_rename find value must be a single identifier.")
    pattern = re.compile(rf"\b{re.escape(identifier)}\b")
    return [
        make_edit(text, match.start(), match.end(), str(recipe["replace"]))
        for match in pattern.finditer(text)
    ]


def plan_anchored_block(text: str, recipe: dict[str, Any]) -> list[PlannedEdit]:
    start_anchor = str(recipe["startAnchor"])
    end_anchor = str(recipe["endAnchor"])
    start_matches = [m.start() for m in re.finditer(re.escape(start_anchor), text)]
    end_matches = [m.start() for m in re.finditer(re.escape(end_anchor), text)]
    if len(start_matches) != 1 or len(end_matches) != 1:
        raise EditToolError("Anchor match must be exact: startAnchor and endAnchor must each occur once.")
    start = start_matches[0]
    end = end_matches[0] + len(end_anchor)
    if end <= start:
        raise EditToolError("endAnchor must appear after startAnchor.")
    return [make_edit(text, start, end, str(recipe["replace"]))]


def make_edit(text: str, start: int, end: int, replacement: str) -> PlannedEdit:
    return PlannedEdit(
        start=start,
        end=end,
        before=text[start:end],
        after=replacement,
        line_start=line_number(text, start),
        line_end=line_number(text, end),
    )


def planned_edits_for(path: Path, text: str, recipe: dict[str, Any]) -> list[PlannedEdit]:
    kind = recipe["kind"]
    if kind == "literal_replace":
        return plan_literal(text, recipe)
    if kind == "regex_replace":
        return plan_regex(text, recipe)
    if kind == "identifier_text_rename":
        return plan_identifier(text, path, recipe)
    return plan_anchored_block(text, recipe)


def apply_edits(text: str, edits: list[PlannedEdit]) -> str:
    result: list[str] = []
    cursor = 0
    for edit in sorted(edits, key=lambda item: item.start):
        result.append(text[cursor:edit.start])
        result.append(edit.after)
        cursor = edit.end
    result.append(text[cursor:])
    return "".join(result)


def risk_flags_for(path: str, recipe: dict[str, Any], text: str, edits: list[PlannedEdit]) -> list[str]:
    flags: list[str] = []
    if recipe["kind"] == "regex_replace":
        flags.append("regex_replace")
    if recipe["kind"] == "identifier_text_rename":
        flags.append("non_semantic_identifier_rename")
    if recipe["kind"] == "anchored_block_replace":
        flags.append("anchored_block_replace")
    if is_generated_path(path) or any(marker in text[:500].lower() for marker in GENERATED_MARKERS):
        flags.append("generated_content")
    if len(edits) > 20:
        flags.append("high_edit_count")
    return flags


def build_plan(root: Path, recipe: dict[str, Any], scope: dict[str, Any]) -> dict[str, Any]:
    validate_recipe(recipe)
    scope_paths = validate_scope(root, scope, recipe)
    candidates = iter_candidate_files(root, scope_paths, recipe)
    max_files = int(recipe["maxFiles"])
    max_edits = int(recipe["maxEdits"])
    files: list[dict[str, Any]] = []
    total_edits = 0
    for path in candidates:
        text = read_text(path)
        if text is None:
            continue
        edits = planned_edits_for(path, text, recipe)
        if not edits:
            continue
        total_edits += len(edits)
        if len(files) + 1 > max_files:
            raise EditToolError(f"Planned file count exceeds maxFiles={max_files}.")
        if total_edits > max_edits:
            raise EditToolError(f"Planned replacement count exceeds maxEdits={max_edits}.")
        planned = apply_edits(text, edits)
        relative = rel_path(root, path)
        files.append(
            {
                "path": relative,
                "originalSha256": sha256_text(text),
                "plannedSha256": sha256_text(planned),
                "edits": [edit.to_json() for edit in edits],
                "riskFlags": risk_flags_for(relative, recipe, text, edits),
            }
        )
    return {
        "schemaVersion": SCHEMA_VERSION,
        "toolVersion": TOOL_VERSION,
        "createdAt": dt.datetime.now(dt.timezone.utc).isoformat(),
        "root": str(root),
        "recipe": recipe,
        "scope": scope,
        "files": files,
        "validation": suggested_validation(files, recipe),
    }


def suggested_validation(files: list[dict[str, Any]], recipe: dict[str, Any]) -> list[str]:
    paths = [file["path"] for file in files]
    validation = ["git diff --check -- " + " ".join(paths)] if paths else ["No validation needed: no changes planned."]
    if any(path.endswith(".cs") for path in paths):
        validation.append("dotnet build Meridian.sln --no-restore /p:EnableWindowsTargeting=true")
    if any(path.endswith((".ts", ".tsx")) for path in paths):
        validation.append("npm --prefix src/Meridian.Ui/dashboard run test")
    if any(path.endswith(".py") for path in paths):
        validation.append("python -m compileall " + " ".join(paths))
    if recipe["kind"] == "identifier_text_rename":
        validation.append("Identifier rename is textual only; run compiler/type tests for touched languages.")
    return validation


def summarize_plan(plan: dict[str, Any]) -> dict[str, Any]:
    files = plan.get("files", [])
    risk_flags = sorted({flag for file in files for flag in file.get("riskFlags", [])})
    return {
        "schemaVersion": plan.get("schemaVersion"),
        "toolVersion": plan.get("toolVersion"),
        "fileCount": len(files),
        "editCount": sum(len(file.get("edits", [])) for file in files),
        "riskFlags": risk_flags,
        "paths": [file.get("path") for file in files],
        "validation": plan.get("validation", []),
    }


def render_markdown_plan(plan: dict[str, Any]) -> str:
    summary = summarize_plan(plan)
    lines = [
        "# AI Edit Plan",
        "",
        f"- Schema: `{plan['schemaVersion']}`",
        f"- Tool: `{plan['toolVersion']}`",
        f"- Root: `{plan['root']}`",
        f"- Files: {summary['fileCount']}",
        f"- Edits: {summary['editCount']}",
        f"- Risk flags: {', '.join(summary['riskFlags']) if summary['riskFlags'] else 'none'}",
        "",
        "## Files",
        "",
    ]
    for file in plan["files"]:
        lines.append(f"### `{file['path']}`")
        lines.append(f"- Matches: {len(file['edits'])}")
        lines.append(f"- Original SHA-256: `{file['originalSha256']}`")
        lines.append(f"- Planned SHA-256: `{file['plannedSha256']}`")
        lines.append(f"- Risk flags: {', '.join(file['riskFlags']) if file['riskFlags'] else 'none'}")
        for index, edit in enumerate(file["edits"][:3], 1):
            lines.append("")
            lines.append(f"Match {index} lines {edit['lineStart']}-{edit['lineEnd']}:")
            lines.append("")
            lines.append("```text")
            lines.append(snippet(edit["before"]))
            lines.append("```")
            lines.append("")
            lines.append("Planned replacement:")
            lines.append("")
            lines.append("```text")
            lines.append(snippet(edit["after"]))
            lines.append("```")
        if len(file["edits"]) > 3:
            lines.append(f"- Additional matches omitted from Markdown preview: {len(file['edits']) - 3}")
        lines.append("")
    lines.append("## Suggested Validation")
    lines.append("")
    for command in plan["validation"]:
        lines.append(f"- `{command}`")
    lines.append("")
    return "\n".join(lines)


def snippet(value: str, limit: int = 600) -> str:
    if len(value) <= limit:
        return value
    return value[:limit] + "\n...[truncated]"


def write_plan(plan: dict[str, Any], output: Path, markdown_output: Path | None) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(plan, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    markdown = markdown_output or output.with_suffix(".md")
    markdown.write_text(render_markdown_plan(plan), encoding="utf-8")


def apply_plan(root: Path, plan_path: Path) -> dict[str, Any]:
    plan = json.loads(plan_path.read_text(encoding="utf-8"))
    if plan.get("schemaVersion") != SCHEMA_VERSION:
        raise EditToolError("Unsupported plan schemaVersion.")
    plan_root = Path(str(plan.get("root", ""))).resolve()
    if plan_root != root.resolve():
        raise EditToolError(f"Plan root does not match current repo root: {plan_root}")
    changed: list[str] = []
    for file in plan.get("files", []):
        path = (root / file["path"]).resolve()
        if not is_within(root, path):
            raise EditToolError(f"Plan path escapes repo root: {file['path']}")
        text = read_text(path)
        if text is None:
            raise EditToolError(f"Cannot read text file: {file['path']}")
        if sha256_text(text) != file["originalSha256"]:
            raise EditToolError(f"Hash drift detected before apply: {file['path']}")
        edits = [
            PlannedEdit(
                start=int(edit["start"]),
                end=int(edit["end"]),
                before=str(edit["before"]),
                after=str(edit["after"]),
                line_start=int(edit["lineStart"]),
                line_end=int(edit["lineEnd"]),
            )
            for edit in file.get("edits", [])
        ]
        for edit in edits:
            if text[edit.start : edit.end] != edit.before:
                raise EditToolError(f"Planned snippet drift detected before apply: {file['path']}")
        planned = apply_edits(text, edits)
        if sha256_text(planned) != file["plannedSha256"]:
            raise EditToolError(f"Planned SHA mismatch for: {file['path']}")
        path.write_bytes(planned.encode("utf-8"))
        changed.append(file["path"])
    return {"applied": True, "fileCount": len(changed), "paths": changed}


def scan_matches(root: Path, recipe: dict[str, Any], scope: dict[str, Any]) -> dict[str, Any]:
    plan = build_plan(root, recipe, scope)
    return summarize_plan(plan)


def emit_status(status: dict[str, Any], json_output: str | None, summary: bool) -> None:
    if json_output:
        Path(json_output).write_text(json.dumps(status, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if summary:
        print(f"files={status.get('fileCount', 0)} edits={status.get('editCount', status.get('fileCount', 0))}")
        risks = status.get("riskFlags")
        if risks:
            print("riskFlags=" + ",".join(risks))
    elif not json_output:
        print(json.dumps(status, indent=2, sort_keys=True))


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", help="Repository root. Defaults to auto-discovery from cwd.")
    subparsers = parser.add_subparsers(dest="mode", required=True)
    for mode in ("scan", "plan"):
        sub = subparsers.add_parser(mode)
        sub.add_argument("--recipe-json")
        sub.add_argument("--recipe-file")
        sub.add_argument("--scope-json")
        sub.add_argument("--scope-file")
        sub.add_argument("--summary", action="store_true")
        sub.add_argument("--json-output")
        if mode == "plan":
            sub.add_argument("--output", required=True)
            sub.add_argument("--markdown-output")
    apply_parser = subparsers.add_parser("apply")
    apply_parser.add_argument("--plan", required=True)
    apply_parser.add_argument("--summary", action="store_true")
    apply_parser.add_argument("--json-output")
    explain_parser = subparsers.add_parser("explain")
    explain_parser.add_argument("--plan", required=True)
    explain_parser.add_argument("--summary", action="store_true")
    explain_parser.add_argument("--json-output")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv or sys.argv[1:])
    try:
        root = Path(args.root).resolve() if args.root else repo_root()
        if not (root / "Meridian.sln").is_file():
            raise EditToolError(f"Root does not contain Meridian.sln: {root}")
        if args.mode in {"scan", "plan"}:
            recipe = load_json_value(args.recipe_json, args.recipe_file, "recipe")
            scope = load_json_value(args.scope_json, args.scope_file, "scope")
            plan = build_plan(root, recipe, scope)
            status = summarize_plan(plan)
            if args.mode == "plan":
                write_plan(plan, Path(args.output), Path(args.markdown_output) if args.markdown_output else None)
                status["planPath"] = str(Path(args.output))
            emit_status(status, args.json_output, args.summary)
            return 0
        if args.mode == "apply":
            status = apply_plan(root, Path(args.plan))
            emit_status(status, args.json_output, args.summary)
            return 0
        plan = json.loads(Path(args.plan).read_text(encoding="utf-8"))
        status = summarize_plan(plan)
        emit_status(status, args.json_output, args.summary)
        return 0
    except (EditToolError, OSError, json.JSONDecodeError, re.error) as exc:
        status = {"ok": False, "error": str(exc)}
        if getattr(args, "json_output", None):
            Path(args.json_output).write_text(json.dumps(status, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
