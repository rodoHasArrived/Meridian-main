#!/usr/bin/env python3
"""Refresh source contracts and their generated views without reviewing a database.

The existing schema-control cataloger owns C# parsing and rendering. This command
combines current source contracts with the retained physical catalog; it never
connects to PostgreSQL, runs migrations, promotes a candidate physical snapshot,
or changes reviewed source-documentation hashes.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tools.schema_control.contracts import build_contract_manifest
from tools.schema_control.dependencies import build_dependency_manifest
from tools.schema_control.render import render_snapshot

MANIFEST = "database/manifest"
DOCS = "docs/generated/database"


def regular_path(root: Path, relative: str) -> Path:
    path = root / relative
    if path.is_symlink() or any(parent.is_symlink() for parent in path.parents if parent.is_relative_to(root)):
        raise ValueError(f"Generation paths must not contain symlinks: {relative}")
    return path


def generate(root: Path, *, check: bool = False) -> list[str]:
    root = root.resolve()

    def load(relative: str) -> dict:
        value = json.loads(regular_path(root, relative).read_text(encoding="utf-8"))
        if not isinstance(value, dict):
            raise ValueError(f"Expected an object: {relative}")
        return value

    config = load("database/schema-control.json")
    outputs = config.get("outputs", {})
    if outputs.get("manifest", MANIFEST) != MANIFEST or outputs.get("docs", DOCS) != DOCS:
        raise ValueError("Changed schema-control output paths require generation policy review")
    catalog = load(f"{MANIFEST}/catalog.json")
    migrations = load(f"{MANIFEST}/migrations.json")
    policies = load(f"{MANIFEST}/policies.json")
    contracts = build_contract_manifest(root, config)
    dependencies = build_dependency_manifest(catalog, contracts, config)
    with tempfile.TemporaryDirectory(prefix="meridian-source-contracts-") as temporary:
        candidate = Path(temporary)
        render_snapshot(candidate, catalog=catalog, migrations=migrations, contracts=contracts,
                        dependencies=dependencies, policy_report=policies, config=config)
        desired = {
            f"{MANIFEST}/{name}": (candidate / "manifest" / name).read_bytes()
            for name in ("contracts.json", "dependencies.json")
        }
        desired.update({f"{DOCS}/{path.relative_to(candidate / 'docs').as_posix()}": path.read_bytes()
                        for path in (candidate / "docs").rglob("*") if path.is_file()})

    # The entire documentation destination is generated by render_snapshot. In
    # particular, remove contract diagram pages that disappear as a set shrinks.
    destination = regular_path(root, DOCS)
    existing = set()
    for path in destination.rglob("*"):
        relative = path.relative_to(root).as_posix()
        regular_path(root, relative)
        if path.is_file():
            existing.add(relative)
    changed = sorted(existing - desired.keys())
    for relative, content in desired.items():
        path = regular_path(root, relative)
        if not path.exists() or path.read_bytes() != content:
            changed.append(relative)
    changed.sort()
    if not check:
        for relative in changed:
            path = regular_path(root, relative)
            if relative in desired:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(desired[relative])
            else:
                path.unlink()
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="Report drift without writing files")
    args = parser.parse_args()
    try:
        changed = generate(args.repo, check=args.check)
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Contract generation failed: {error}", file=sys.stderr)
        return 2
    for relative in changed:
        print(f"{'Stale' if args.check else 'Updated'}: {relative}")
    print(f"Source contract generation: {len(changed)} changed outputs; retained physical catalog")
    return 1 if args.check and changed else 0


if __name__ == "__main__":
    raise SystemExit(main())
