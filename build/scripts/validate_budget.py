#!/usr/bin/env python3
"""
validate_budget.py — CI allocation-budget enforcement script.

Reads a ``perf-budgets.json`` file generated by PerformanceBudgetRegistry.ExportJson()
and compares actual BenchmarkDotNet results against the declared budgets.

An absent measurement is not a passing measurement. A benchmark harness that crashes,
is skipped, or writes nothing at all produces the same empty result set as a run where
every budget was comfortably met, so a gate that ignores missing rows reports green for
a lane that measured nothing. This script therefore treats three things as failures:
a results directory that does not exist, a directory holding no parsable BenchmarkDotNet
report, and any non-SIMD budget with no matching result row. A budget that is knowingly
not measured in a lane must be named explicitly with ``--allow-unmeasured``.

Usage
-----
    python3 build/scripts/validate_budget.py \\
        --bdn-results ./BenchmarkDotNet.Artifacts/current/results \\
        --budget-json ./BenchmarkDotNet.Artifacts/current/perf-budgets.json \\
        [--fail-on-violation] \\
        [--allow-unmeasured STAGE_NAME]... \\
        [--json-output ./budget-evidence.json]

Exit codes
----------
    0  — every budget measured and within limits (or --fail-on-violation not set)
    1  — violations or unmeasured budgets when --fail-on-violation is set
    2  — input file not found, JSON parse error, or no benchmark results at all
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import dataclass
from pathlib import Path


# ---------------------------------------------------------------------------
# Data types
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class Budget:
    stage_name: str
    max_allocated_bytes_per_event: int
    max_mean_nanos_per_event: int
    requires_simd: bool


@dataclass(frozen=True)
class BdnResult:
    method_name: str
    mean_ns: float
    allocated_bytes: int


@dataclass(frozen=True)
class BudgetViolation:
    stage_name: str
    budget: Budget
    result: BdnResult
    allocated_over_by: int
    mean_over_by: float


# ---------------------------------------------------------------------------
# Core functions
# ---------------------------------------------------------------------------

def load_budgets(budget_json_path: str) -> dict[str, Budget]:
    """
    Load budgets from the perf-budgets.json generated by
    PerformanceBudgetRegistry.ExportJson().

    Returns a mapping of {stage_name: Budget}.
    """
    path = Path(budget_json_path)
    if not path.exists():
        print(f"[validate_budget] ERROR: budget file not found: {budget_json_path}", file=sys.stderr)
        sys.exit(2)

    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        print(f"[validate_budget] ERROR: could not parse {budget_json_path}: {exc}", file=sys.stderr)
        sys.exit(2)

    budgets: dict[str, Budget] = {}
    for entry in raw:
        b = Budget(
            stage_name=entry["stage_name"],
            max_allocated_bytes_per_event=entry["max_allocated_bytes_per_event"],
            max_mean_nanos_per_event=entry["max_mean_nanos_per_event"],
            requires_simd=entry.get("requires_simd", False),
        )
        budgets[b.stage_name] = b
    return budgets


def load_bdn_results(results_dir: str) -> list[BdnResult]:
    """
    Scan *results_dir* for BDN JSON result files (``*-report-full.json`` or
    ``*-report.json``) and return a flat list of per-benchmark rows.

    BDN full-report schema (simplified):
        { "Benchmarks": [ { "FullName": "...", "Statistics": { "Mean": ... },
                             "Memory": { "BytesAllocatedPerOperation": ... } }, ... ] }

    Exits 2 when the directory is absent or yields no benchmark rows: a harness that
    produced nothing is indistinguishable from one that measured everything successfully
    if the empty case is allowed to pass.
    """
    results_path = Path(results_dir)
    if not results_path.exists():
        print(
            f"[validate_budget] ERROR: results directory not found: {results_dir}. "
            "The benchmark harness produced no measurements, which cannot be reported as a pass.",
            file=sys.stderr,
        )
        sys.exit(2)

    rows: list[BdnResult] = []

    # Prefer full reports; fall back to standard reports
    json_files = list(results_path.glob("*-report-full.json"))
    if not json_files:
        json_files = list(results_path.glob("*-report.json"))

    for jf in json_files:
        try:
            data = json.loads(jf.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            continue

        for bench in data.get("Benchmarks", []):
            method_name: str = bench.get("FullName") or bench.get("Method") or ""
            stats = bench.get("Statistics") or {}
            memory = bench.get("Memory") or {}

            # A benchmark that failed or did not complete still emits an entry, but without
            # Statistics.Mean or Memory.BytesAllocatedPerOperation. Defaulting those to zero
            # would present it as an instantaneous, zero-allocation success and let it satisfy
            # any budget — the same false green an absent result set produces.
            mean_ns = stats.get("Mean")
            allocated_bytes = memory.get("BytesAllocatedPerOperation")
            if not isinstance(mean_ns, (int, float)) or not isinstance(allocated_bytes, (int, float)):
                print(
                    f"[validate_budget] WARNING: '{method_name or jf.name}' has no mean/allocation "
                    "statistics; treating it as unmeasured.",
                    file=sys.stderr,
                )
                continue

            rows.append(BdnResult(
                method_name=method_name,
                mean_ns=float(mean_ns),
                allocated_bytes=int(allocated_bytes),
            ))

    if not rows:
        print(
            f"[validate_budget] ERROR: no benchmark results parsed from {results_dir}. "
            "An absent scan is not a clean scan.",
            file=sys.stderr,
        )
        sys.exit(2)

    return rows


def check_budgets(budgets: dict[str, Budget], results: list[BdnResult]) -> list[BudgetViolation]:
    """
    Compare each result against its matching budget entry.

    Matching uses a two-pass strategy:
    1. Full normalised stage_name as a substring of the normalised method name.
    2. Token fallback: any ``_``-delimited token of the stage_name (length ≥ 5) that
       appears case-insensitively in the method name.  This handles cases where stage
       names use abbreviated terms that differ from the BDN class/method names
       (e.g. "DedupKey" vs "DeduplicationKey").

    SIMD entries are skipped.  Budgets with no matching result are reported separately by
    :func:`find_unmeasured_budgets`, not here.

    Returns a list of violations (empty = all measured budgets within limits).
    """
    violations: list[BudgetViolation] = []

    for stage_name, budget in budgets.items():
        if budget.requires_simd:
            continue  # SIMD benchmarks excluded from CI gate

        best = best_result_for(stage_name, results)
        if best is None:
            continue  # Reported as an unmeasured budget instead of a violation.

        alloc_over = best.allocated_bytes - budget.max_allocated_bytes_per_event
        mean_over = best.mean_ns - budget.max_mean_nanos_per_event

        if alloc_over > 0 or (budget.max_mean_nanos_per_event < 2**63 - 1 and mean_over > 0):
            violations.append(BudgetViolation(
                stage_name=stage_name,
                budget=budget,
                result=best,
                allocated_over_by=max(0, alloc_over),
                mean_over_by=max(0.0, mean_over),
            ))

    return violations


def best_result_for(stage_name: str, results: list[BdnResult]) -> BdnResult | None:
    """Return the lowest-allocating result matching *stage_name*, or None when unmeasured."""
    matching = [r for r in results if _stage_matches_method(stage_name, r.method_name)]
    if not matching:
        return None
    # Use the row with lowest allocation (most optimistic reading)
    return min(matching, key=lambda r: r.allocated_bytes)


def find_unmeasured_budgets(
    budgets: dict[str, Budget],
    results: list[BdnResult],
    allow_unmeasured: set[str] | None = None,
) -> list[str]:
    """
    Return the non-SIMD budgets that no benchmark result measured.

    A budget nobody measured provides no protection at all, and before this check the gate
    reported it identically to a budget that was measured and met. Stages that a lane
    deliberately does not measure must be named in *allow_unmeasured* so the omission is a
    reviewed decision rather than an accident of which benchmarks happened to run.
    """
    allowed = allow_unmeasured or set()
    return sorted(
        stage_name
        for stage_name, budget in budgets.items()
        if not budget.requires_simd
        and stage_name not in allowed
        and best_result_for(stage_name, results) is None
    )


def find_waived_budgets(
    budgets: dict[str, Budget],
    results: list[BdnResult],
    allow_unmeasured: set[str] | None = None,
) -> list[str]:
    """
    Return the budgets that ``--allow-unmeasured`` waived and no result measured.

    A waiver suppresses the failure, not the coverage gap. Reporting only *unmeasured* left the
    waived stages out of every count and out of ``unmeasured_stages``, so the evidence file
    recorded zero unmeasured budgets and the summary concluded that all budgets were measured —
    letting a release reviewer read a waiver as a measurement.
    """
    allowed = allow_unmeasured or set()
    return sorted(
        stage_name
        for stage_name, budget in budgets.items()
        if not budget.requires_simd
        and stage_name in allowed
        and best_result_for(stage_name, results) is None
    )


def _stage_matches_method(stage_name: str, method_name: str) -> bool:
    """
    Return ``True`` if *stage_name* is considered to correspond to *method_name*.

    Pass 1: full normalised stage_name appears as a substring of the normalised
    method name (handles most well-named cases).
    Pass 2: token fallback — any ``_``-delimited token of *stage_name* with length ≥ 5
    that appears case-insensitively in the normalised method name.  Needed when stage
    names use abbreviations different from BDN class/method names.
    """
    norm_method = _normalise(method_name)
    if _normalise(stage_name) in norm_method:
        return True
    tokens = [t.lower() for t in stage_name.split("_") if len(t) >= 5]
    return any(t in norm_method for t in tokens)


def render_summary(
    violations: list[BudgetViolation],
    budgets: dict[str, Budget],
    results: list[BdnResult],
    unmeasured: list[str],
) -> str:
    """
    Render a Markdown summary table suitable for appending to ``$GITHUB_STEP_SUMMARY``.
    Always emits a table with all non-SIMD budgets; violations are highlighted with ❌ and
    budgets nobody measured with ⛔ so an empty lane cannot read as a clean one.

    *results* is required: without the measured rows the renderer cannot tell a budget that
    passed from one that nothing measured, which is the distinction this report exists to make.
    """
    unmeasured_set = set(unmeasured)

    lines: list[str] = []
    lines.append("## Performance Budget Report\n")

    lines.append("| Stage | Budget (bytes/event) | Actual (bytes/event) | Status |")
    lines.append("|-------|---------------------|---------------------|--------|")

    for stage_name, budget in sorted(budgets.items()):
        if budget.requires_simd:
            lines.append(f"| `{stage_name}` | {budget.max_allocated_bytes_per_event} | _SIMD — excluded_ | ⚠️ SIMD |")
            continue

        violation = next((v for v in violations if v.stage_name == stage_name), None)
        if violation:
            actual: object = violation.result.allocated_bytes
            status = f"❌ +{violation.allocated_over_by} bytes over budget"
        elif stage_name in unmeasured_set:
            actual = "—"
            status = "⛔ No benchmark measured this budget"
        else:
            best = best_result_for(stage_name, results)
            actual = best.allocated_bytes if best is not None else "—"
            status = "✅ Pass" if best is not None else "➖ Unmeasured (declared)"

        lines.append(f"| `{stage_name}` | {budget.max_allocated_bytes_per_event} | {actual} | {status} |")

    # Every non-SIMD budget with no result that is not already reported as unmeasured was
    # waived with --allow-unmeasured.
    waived = [
        stage_name
        for stage_name, budget in sorted(budgets.items())
        if not budget.requires_simd
        and stage_name not in unmeasured_set
        and best_result_for(stage_name, results) is None
    ]

    if violations:
        lines.append(f"\n**{len(violations)} violation(s) detected.**\n")
    if unmeasured_set:
        lines.append(
            f"\n**{len(unmeasured_set)} budget(s) had no benchmark result.** "
            "An unmeasured budget enforces nothing; run the benchmark or declare the stage with "
            "`--allow-unmeasured`.\n"
        )
    if waived:
        # A waiver is not a measurement. Saying "all budgets measured" while stages carry
        # `--allow-unmeasured` would let waived coverage read as verified coverage.
        lines.append(
            f"\n**{len(waived)} budget(s) waived with `--allow-unmeasured` and still unmeasured:** "
            + ", ".join(f"`{stage}`" for stage in waived)
            + ".\n"
        )
    if not violations and not unmeasured_set:
        lines.append(
            "\n**All measured budgets within limits.** ✅\n"
            if waived
            else "\n**All budgets measured and within limits.** ✅\n"
        )

    return "\n".join(lines)


def build_evidence(
    budgets: dict[str, Budget],
    results: list[BdnResult],
    violations: list[BudgetViolation],
    unmeasured: list[str],
) -> dict:
    """Build the machine-readable record of what this lane actually measured."""
    stages = []
    for stage_name, budget in sorted(budgets.items()):
        best = None if budget.requires_simd else best_result_for(stage_name, results)
        violation = next((v for v in violations if v.stage_name == stage_name), None)
        stages.append(
            {
                "stage_name": stage_name,
                "requires_simd": budget.requires_simd,
                "max_allocated_bytes_per_event": budget.max_allocated_bytes_per_event,
                "max_mean_nanos_per_event": budget.max_mean_nanos_per_event,
                "measured": best is not None,
                "actual_allocated_bytes": best.allocated_bytes if best else None,
                "actual_mean_nanos": best.mean_ns if best else None,
                "matched_benchmark": best.method_name if best else None,
                "status": (
                    "simd-excluded"
                    if budget.requires_simd
                    else "violation"
                    if violation
                    else "unmeasured"
                    if stage_name in set(unmeasured)
                    else "pass"
                    if best is not None
                    else "unmeasured-declared"
                ),
            }
        )

    waived = [s["stage_name"] for s in stages if s["status"] == "unmeasured-declared"]

    return {
        "benchmark_result_rows": len(results),
        "budget_count": len(budgets),
        "violation_count": len(violations),
        "unmeasured_count": len(unmeasured),
        "unmeasured_stages": unmeasured,
        # A waived stage is unmeasured too; it just does not fail the lane. Counting it nowhere
        # let a machine consumer read "unmeasured_count: 0" as full coverage.
        "waived_unmeasured_count": len(waived),
        "waived_unmeasured_stages": waived,
        "measured_count": sum(1 for s in stages if s["measured"]),
        "stages": stages,
    }


def _normalise(s: str) -> str:
    return s.lower().replace("_", "").replace(".", "").replace(" ", "")


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Validate BDN benchmark results against declared allocation budgets.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "--bdn-results",
        required=True,
        metavar="DIR",
        help="Directory containing BDN JSON result files (e.g. ./BenchmarkDotNet.Artifacts/current/results)",
    )
    parser.add_argument(
        "--budget-json",
        required=True,
        metavar="FILE",
        help="Path to perf-budgets.json generated by PerformanceBudgetRegistry.ExportJson()",
    )
    parser.add_argument(
        "--fail-on-violation",
        action="store_true",
        default=False,
        help="Exit with code 1 if any budget is exceeded or left unmeasured",
    )
    parser.add_argument(
        "--allow-unmeasured",
        action="append",
        default=[],
        metavar="STAGE_NAME",
        help="Declare a budget this lane deliberately does not measure (repeatable)",
    )
    parser.add_argument(
        "--json-output",
        metavar="FILE",
        help="Write machine-readable budget evidence (measured values, unmeasured stages) to FILE",
    )

    args = parser.parse_args()

    budgets = load_budgets(args.budget_json)
    results = load_bdn_results(args.bdn_results)
    violations = check_budgets(budgets, results)
    unmeasured = find_unmeasured_budgets(budgets, results, set(args.allow_unmeasured))

    summary = render_summary(violations, budgets, results, unmeasured)
    print(summary)

    if args.json_output:
        evidence = build_evidence(budgets, results, violations, unmeasured)
        try:
            output_path = Path(args.json_output)
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_text(json.dumps(evidence, indent=2) + "\n", encoding="utf-8")
        except OSError as exc:
            print(f"[validate_budget] ERROR: could not write {args.json_output}: {exc}", file=sys.stderr)
            return 2

    # Append to GitHub Actions step summary when running in CI
    github_summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if github_summary:
        try:
            with open(github_summary, "a", encoding="utf-8") as f:
                f.write(summary + "\n")
        except OSError:
            pass  # Non-fatal if we can't write the summary

    if args.fail_on_violation and (violations or unmeasured):
        if violations:
            print(
                f"\n[validate_budget] FAILED: {len(violations)} budget violation(s). See table above.",
                file=sys.stderr,
            )
        if unmeasured:
            print(
                f"[validate_budget] FAILED: {len(unmeasured)} budget(s) had no benchmark result: "
                + ", ".join(unmeasured),
                file=sys.stderr,
            )
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
