#!/usr/bin/env python3
"""Generate the dashboard UiApiRoutes mirror from the C# contracts source.

Run with --check to verify the committed mirror matches the contracts source
without rewriting it (CI drift gate); exits 1 when regeneration is needed.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE_FILE = REPO_ROOT / "src" / "Meridian.Contracts" / "Api" / "UiApiRoutes.cs"
OUTPUT_FILE = (
    REPO_ROOT
    / "src"
    / "Meridian.Ui"
    / "dashboard"
    / "src"
    / "lib"
    / "ui-api-routes.generated.ts"
)

CONSTANT_PATTERN = re.compile(
    r"^\s*public\s+const\s+string\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*\"(?P<route>[^\"]*)\";",
    re.MULTILINE,
)


def extract_routes(source: str) -> list[tuple[str, str]]:
    return [(match.group("name"), match.group("route")) for match in CONSTANT_PATTERN.finditer(source)]


def render(routes: list[tuple[str, str]]) -> str:
    if not routes:
        raise ValueError(f"No UiApiRoutes constants found in {SOURCE_FILE}")

    lines = [
        "// <auto-generated>",
        "// Generated by build/scripts/generate-ui-api-routes-ts.py from src/Meridian.Contracts/Api/UiApiRoutes.cs.",
        "// </auto-generated>",
        "",
        "export const UI_API_ROUTES = {",
    ]
    for name, route in routes:
        lines.append(f"  {name}: {json.dumps(route)},")
    lines.extend(["} as const;", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the generated file is current instead of rewriting it",
    )
    args = parser.parse_args()

    source = SOURCE_FILE.read_text(encoding="utf-8")
    rendered = render(extract_routes(source))

    if args.check:
        current = OUTPUT_FILE.read_text(encoding="utf-8") if OUTPUT_FILE.exists() else ""
        if current != rendered:
            print(
                f"DRIFT: {OUTPUT_FILE.relative_to(REPO_ROOT)} is stale relative to "
                f"{SOURCE_FILE.relative_to(REPO_ROOT)}.\n"
                "Run: python3 build/scripts/generate-ui-api-routes-ts.py",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {OUTPUT_FILE.relative_to(REPO_ROOT)} is current.")
        return 0

    OUTPUT_FILE.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
