#!/usr/bin/env python3
"""Generate the dashboard UiApiRoutes mirror from the C# contracts source."""

from __future__ import annotations

import json
import re
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE_FILE = REPO_ROOT / "src" / "Meridian.Contracts" / "Api" / "UiApiRoutes.cs"
OUTPUT_FILE = (
    REPO_ROOT
    / "src"
    / "Meridian.Ui"
    / "dashboard"
    / "src"
    / "lib"
    / "ui-api-routes.generated.ts"
)

CONSTANT_PATTERN = re.compile(
    r"^\s*public\s+const\s+string\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*\"(?P<route>[^\"]*)\";",
    re.MULTILINE,
)


def extract_routes(source: str) -> list[tuple[str, str]]:
    return [(match.group("name"), match.group("route")) for match in CONSTANT_PATTERN.finditer(source)]


def render(routes: list[tuple[str, str]]) -> str:
    if not routes:
        raise ValueError(f"No UiApiRoutes constants found in {SOURCE_FILE}")

    lines = [
        "// <auto-generated>",
        "// Generated by build/scripts/generate-ui-api-routes-ts.py from src/Meridian.Contracts/Api/UiApiRoutes.cs.",
        "// </auto-generated>",
        "",
        "export const UI_API_ROUTES = {",
    ]
    for name, route in routes:
        lines.append(f"  {name}: {json.dumps(route)},")
    lines.extend(["} as const;", ""])
    return "\n".join(lines)


def main() -> None:
    source = SOURCE_FILE.read_text(encoding="utf-8")
    OUTPUT_FILE.write_text(render(extract_routes(source)), encoding="utf-8")


if __name__ == "__main__":
    main()
