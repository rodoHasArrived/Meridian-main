#!/usr/bin/env python3
"""Generate browser workspace metadata from the shared C# workspace catalog.

Run with --check to verify the committed mirror matches the contracts source
without rewriting it (CI drift gate); exits 1 when regeneration is needed.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE_FILE = REPO_ROOT / "src" / "Meridian.Contracts" / "Workstation" / "WorkstationWorkspaceCatalog.cs"
OUTPUT_FILE = (
    REPO_ROOT
    / "src"
    / "Meridian.Ui"
    / "dashboard"
    / "src"
    / "lib"
    / "workspace-catalog.generated.ts"
)

WORKSPACE_NAMES = [
    "Trading",
    "Portfolio",
    "Accounting",
    "Reporting",
    "Strategy",
    "Data",
    "Settings",
]

CONSTANT_PATTERN = re.compile(
    r"^\s*public\s+const\s+string\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*\"(?P<value>[^\"]*)\";",
    re.MULTILINE,
)


def extract_constants(source: str) -> dict[str, str]:
    return {match.group("name"): match.group("value") for match in CONSTANT_PATTERN.finditer(source)}


def render(constants: dict[str, str]) -> str:
    entries: list[dict[str, str]] = []
    for name in WORKSPACE_NAMES:
        entries.append(
            {
                "key": constants[f"{name}Key"],
                "label": constants[f"{name}Label"],
                "description": constants[f"{name}BrowserDescription"],
                "status": constants[f"{name}BrowserStatus"],
            }
        )

    lines = [
        "// <auto-generated>",
        "// Generated by build/scripts/generate-workspace-catalog-ts.py from src/Meridian.Contracts/Workstation/WorkstationWorkspaceCatalog.cs.",
        "// </auto-generated>",
        "",
        "export const WORKSPACE_DEFINITIONS = [",
    ]
    for entry in entries:
        lines.append("  {")
        lines.append(f"    key: {json.dumps(entry['key'])},")
        lines.append(f"    label: {json.dumps(entry['label'])},")
        lines.append(f"    description: {json.dumps(entry['description'])},")
        lines.append(f"    status: {json.dumps(entry['status'])}")
        lines.append("  },")
    lines.extend(["] as const;", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the generated file is current instead of rewriting it",
    )
    args = parser.parse_args()

    source = SOURCE_FILE.read_text(encoding="utf-8")
    rendered = render(extract_constants(source))

    if args.check:
        current = OUTPUT_FILE.read_text(encoding="utf-8") if OUTPUT_FILE.exists() else ""
        if current != rendered:
            print(
                f"DRIFT: {OUTPUT_FILE.relative_to(REPO_ROOT)} is stale relative to "
                f"{SOURCE_FILE.relative_to(REPO_ROOT)}.\n"
                "Run: python3 build/scripts/generate-workspace-catalog-ts.py",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {OUTPUT_FILE.relative_to(REPO_ROOT)} is current.")
        return 0

    OUTPUT_FILE.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
