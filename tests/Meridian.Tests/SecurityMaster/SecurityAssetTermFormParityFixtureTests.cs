using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using FluentAssertions;
using Meridian.Contracts.SecurityMaster;

namespace Meridian.Tests.SecurityMaster;

/// <summary>
/// The parity contract between the shared C# term form model
/// (<see cref="SecurityAssetTermFormModel"/> over <see cref="SecurityAssetClassRegistry"/>) and the
/// browser mirror (<c>security-passport-schema-fields.view-model.ts</c>). The committed fixture
/// records, for every registry asset class, the served field definitions, the pickable scalar
/// fields in form order and each field's closed value choices, plus the validation verdict of every
/// editor kind (required and optional) over a fixed input corpus. The dashboard's
/// <c>security-passport-schema-fields.parity.test.ts</c> replays the same fixture through the
/// TypeScript mirror, so a schema or form-rule change that regenerates this fixture fails the
/// browser suite until the mirror follows — the parity contract D9 asks for, instead of two
/// hand-maintained copies that drift silently.
/// </summary>
/// <remarks>
/// <para>The corpus pins the rules on representative operator input. It deliberately leaves out
/// inputs whose verdicts depend on host parsing esoterica the mirror does not reproduce
/// (misplaced thousands separators such as <c>",5"</c>, and values beyond
/// <c>decimal.MaxValue</c>): the server-side governed validator stays authoritative for those.</para>
/// <para>A missing or mismatched fixture writes
/// <c>security-asset-term-form-parity.received.json</c> beside the test binaries and fails; it
/// never skips. Replace the committed fixture with the received file only when the form-model or
/// schema change is intended, and update the TypeScript mirror until its parity suite passes.</para>
/// </remarks>
[Trait("Category", "Unit")]
public sealed class SecurityAssetTermFormParityFixtureTests
{
    private const string FixtureRepoPath =
        "src/Meridian.Ui/dashboard/src/test/fixtures/security-asset-term-form-parity.json";

    private const string ReceivedFileName = "security-asset-term-form-parity.received.json";

    // One shared corpus applied to every editor kind, so a rule picking up a new input class is a
    // visible fixture change. Grouped by the rule it probes; every editor sees every value.
    private static readonly string[] ValidationCorpus =
    [
        "", "   ",
        "1.5", "-2.75", "+3", "1,234.56", ".5", "5.", "1e5", "abc", "NaN",
        "7", "-12", "+9", "007", "1.0", "9223372036854775807", "9223372036854775808",
        "2026-01-31", "2024-02-29", "2026-02-29", "2026-02-30", "2026-13-01", "2026-1-05",
        "2026-01-31T00:00:00", "0001-01-01",
        "true", "false", "TRUE", "yes",
        "Alpha", "alpha", "__not-a-choice__",
    ];

    [Fact]
    public void Committed_parity_fixture_matches_the_form_model()
    {
        var generated = GenerateFixtureJson();
        var fixturePath = Path.Combine(
            FindRepositoryRoot(),
            FixtureRepoPath.Replace('/', Path.DirectorySeparatorChar));

        var committed = File.Exists(fixturePath) ? File.ReadAllText(fixturePath) : null;
        if (committed is not null && Normalize(committed) == Normalize(generated))
        {
            return;
        }

        var receivedPath = Path.Combine(AppContext.BaseDirectory, ReceivedFileName);
        File.WriteAllText(receivedPath, generated, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));

        false.Should().BeTrue(
            $"the committed parity fixture at {FixtureRepoPath} is " +
            $"{(committed is null ? "missing" : "stale")}; the " +
            $"regenerated fixture was written to {receivedPath}. Replace the committed file with it " +
            "only when the schema or form-rule change is intended, then make the dashboard parity " +
            "suite (security-passport-schema-fields.parity.test.ts) pass against it");
    }

    private static string GenerateFixtureJson()
    {
        var root = new JsonObject
        {
            ["comment"] =
                "Generated by SecurityAssetTermFormParityFixtureTests from SecurityAssetClassRegistry " +
                "and SecurityAssetTermFormModel. Do not edit by hand: run the test and copy the " +
                "received file it writes on mismatch.",
            ["assetClasses"] = new JsonArray(
                SecurityAssetClassRegistry.ToDtos().Select(BuildClassNode).ToArray()),
            ["validationContracts"] = BuildValidationContracts(),
        };

        var json = root.ToJsonString(new JsonSerializerOptions
        {
            WriteIndented = true,
            Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        });
        return json + "\n";
    }

    private static JsonNode BuildClassNode(SecurityAssetClassDefinitionDto dto)
    {
        var pickable = SecurityAssetTermFormModel.PickableFields(dto);

        return new JsonObject
        {
            ["assetClass"] = dto.AssetClass,
            ["termsVersion"] = dto.TermsVersion,
            ["lotUnit"] = dto.LotUnit.ToString(),
            ["cashFlowBehavior"] = dto.CashFlowBehavior.ToString(),
            ["fields"] = new JsonArray(dto.Fields.Select(BuildFieldNode).ToArray()),
            ["pickableFieldKeys"] = new JsonArray(
                pickable.Select(field => (JsonNode?)field.Key).ToArray()),
            ["valueChoicesByKey"] = new JsonObject(pickable.Select(field =>
                new KeyValuePair<string, JsonNode?>(
                    field.Key,
                    new JsonArray(SecurityAssetTermFormModel.ValueChoices(field)
                        .Select(choice => (JsonNode?)choice).ToArray())))),
        };
    }

    private static JsonNode? BuildFieldNode(SecurityAssetTermFieldDefinitionDto field)
        => new JsonObject
        {
            ["key"] = field.Key,
            ["fieldPath"] = field.FieldPath,
            ["label"] = field.Label,
            ["type"] = field.Type,
            ["editor"] = field.Editor.ToString(),
            ["group"] = field.Group,
            ["order"] = field.Order,
            ["required"] = field.Required,
            ["scalarEditable"] = field.ScalarEditable,
            ["choices"] = new JsonArray(field.Choices.Select(choice => (JsonNode?)choice).ToArray()),
            ["aliases"] = new JsonArray(field.Aliases.Select(alias => (JsonNode?)alias).ToArray()),
            ["role"] = field.Role.ToString(),
        };

    private static JsonArray BuildValidationContracts()
    {
        var contracts = new JsonArray();
        foreach (var editor in Enum.GetValues<SecurityAssetTermEditorKind>())
        {
            foreach (var required in new[] { true, false })
            {
                var choices = editor is SecurityAssetTermEditorKind.Choice or SecurityAssetTermEditorKind.Convention
                    ? new[] { "Alpha", "Beta" }
                    : Array.Empty<string>();

                var field = new SecurityAssetTermFieldDefinitionDto(
                    Key: "testField",
                    FieldPath: "assetSpecificTerms.testField",
                    Label: "Test field",
                    Type: editor.ToString(),
                    Editor: editor,
                    Group: "Parity",
                    Order: 0,
                    Required: required,
                    ScalarEditable: true,
                    Choices: choices,
                    Aliases: []);

                contracts.Add(new JsonObject
                {
                    ["editor"] = editor.ToString(),
                    ["required"] = required,
                    ["label"] = field.Label,
                    ["choices"] = new JsonArray(choices.Select(choice => (JsonNode?)choice).ToArray()),
                    ["cases"] = new JsonArray(ValidationCorpus.Select(value => (JsonNode?)new JsonObject
                    {
                        ["value"] = value,
                        ["error"] = SecurityAssetTermFormModel.Validate(field, value),
                    }).ToArray()),
                });
            }
        }

        return contracts;
    }

    private static string Normalize(string text) => text.Replace("\r\n", "\n", StringComparison.Ordinal);

    private static string FindRepositoryRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null)
        {
            if (File.Exists(Path.Combine(directory.FullName, "Meridian.sln")))
            {
                return directory.FullName;
            }

            directory = directory.Parent;
        }

        throw new InvalidOperationException("Unable to locate Meridian repository root from test output directory.");
    }
}
