    {
        var grid = new ReportWriterGridDefinitionDto(
            "if-errors",
            "If errors",
            ReportWriterGridKindDto.Detail,
            RowFields: ["symbol"],
            Metrics: [new ReportWriterMetricDefinitionDto("a", "a")],
