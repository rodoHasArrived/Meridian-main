    [Fact]
    public void RenderGrids_BuildsPivotTopNContributionAndFormulaOutputs()
    {
        var rows = new[]
        {
            Row(("security", "AAPL"), ("sector", "Technology"), ("strategy", "Core"), ("marketValue", "100"), ("pnl", "15")),
            Row(("security", "MSFT"), ("sector", "Technology"), ("strategy", "Core"), ("marketValue", "200"), ("pnl", "5")),
            Row(("security", "TLT"), ("sector", "Rates"), ("strategy", "Hedge"), ("marketValue", "50"), ("pnl", "-3")),
            Row(("security", "GLD"), ("sector", "Commodities"), ("strategy", "Hedge"), ("marketValue", "50"), ("pnl", "2"))
        };
        var grids = new[]
        {
            new ReportWriterGridDefinitionDto(
                "sector-pivot",
                "Sector Pivot",
                ReportWriterGridKindDto.Pivot,
                RowFields: ["sector"],
                Metrics:
                [
                    new ReportWriterMetricDefinitionDto("marketValue", "marketValue"),
                    new ReportWriterMetricDefinitionDto("pnl", "pnl")
                ],
                Formulas:
                [
                    new ReportWriterFormulaDefinitionDto("returnPct", "{pnl} / {marketValue} * 100")
                ],
                SortBy: "marketValue"),
            new ReportWriterGridDefinitionDto(
                "top-winners",
                "Top Winners",
                ReportWriterGridKindDto.TopN,
                RowFields: ["security"],
                Metrics: [new ReportWriterMetricDefinitionDto("pnl", "pnl")],
                TopN: 2,
                SortBy: "pnl"),
            new ReportWriterGridDefinitionDto(
                "strategy-contribution",
                "Strategy Contribution",
                ReportWriterGridKindDto.Contribution,
                RowFields: ["strategy"],
                Metrics: [new ReportWriterMetricDefinitionDto("marketValue", "marketValue")])
        };

        var rendered = ReportWriterGridEngine.RenderGrids(grids, rows);

        rendered.Should().HaveCount(3);
        var pivot = rendered.Single(grid => grid.GridId == "sector-pivot");
        pivot.Columns.Select(column => column.Key).Should().ContainInOrder("sector", "marketValue", "pnl", "returnPct");
        pivot.Rows.Should().Contain(row =>
            row.Values["sector"] == "Technology" &&
            row.Values["marketValue"] == "300" &&
            row.Values["pnl"] == "20" &&
            row.Values["returnPct"] == "6.666667");
        pivot.Lineage.Should().NotBeNull();
        pivot.Lineage!.InputRowCount.Should().Be(4);
        pivot.Lineage.OutputRowCount.Should().Be(3);
        pivot.Lineage.SourceFields.Should().Equal("marketValue", "pnl", "sector");
        pivot.Lineage.Metrics.Should().Contain(metric =>
            metric.Name == "marketValue" &&
            metric.SourceField == "marketValue" &&
            metric.Function == ReportWriterAggregateFunctionDto.Sum.ToString());
        pivot.Lineage.Formulas.Should().Contain(formula =>
            formula.Name == "returnPct" &&
            formula.Expression == "{pnl} / {marketValue} * 100" &&
            formula.SourceFields.Count == 2 &&
            formula.SourceFields[0] == "marketValue" &&
            formula.SourceFields[1] == "pnl");
        pivot.DataDictionary.Should().NotBeNull();
        pivot.DataDictionary!.Should().Contain(field =>
            field.Key == "marketValue" &&
            field.SourceField == "marketValue" &&
            field.DataType == "decimal" &&
            !field.IsGenerated);
        pivot.DataDictionary.Should().Contain(field =>
            field.Key == "returnPct" &&
            field.Role == "formula" &&
            field.SourceField == "marketValue;pnl" &&
            field.IsGenerated &&
            field.Description.Contains("generated by the retained report-writer grid", StringComparison.OrdinalIgnoreCase));
        pivot.ValidationChecks.Should().NotBeNull();
        pivot.ValidationChecks!.Should().Contain(check =>
            check.CheckId == "column-dictionary" &&
            check.Status == "Passed");
        pivot.ValidationChecks.Should().Contain(check =>
            check.CheckId == "source-field-lineage" &&
            check.Status == "Passed");

        var top = rendered.Single(grid => grid.GridId == "top-winners");
        top.Rows.Select(row => row.Values["security"]).Should().Equal("AAPL", "MSFT");

        var contribution = rendered.Single(grid => grid.GridId == "strategy-contribution");
        contribution.Columns.Should().Contain(column => column.Key == "contributionPercent" && column.Role == "formula");
        contribution.Rows.Should().Contain(row =>
            row.Values["strategy"] == "Core" &&
            row.Values["marketValue"] == "300" &&
            row.Values["contributionPercent"] == "75");
    }

    [Fact]
    public void RenderGrids_PivotWithColumnFieldsBuildsCrosstabMetricColumns()
    {
        var rows = new[]
        {
            Row(("sector", "Technology"), ("region", "US"), ("marketValue", "100"), ("pnl", "10")),
            Row(("sector", "Technology"), ("region", "EU"), ("marketValue", "50"), ("pnl", "5")),
            Row(("sector", "Rates"), ("region", "US"), ("marketValue", "40"), ("pnl", "-2"))
        };
        var grids = new[]
        {
            new ReportWriterGridDefinitionDto(
                "sector-region-pivot",
                "Sector Region Pivot",
                ReportWriterGridKindDto.Pivot,
                RowFields: ["sector"],
                ColumnFields: ["region"],
                Metrics:
                [
                    new ReportWriterMetricDefinitionDto("marketValue", "marketValue"),
                    new ReportWriterMetricDefinitionDto("pnl", "pnl")
                ],
                Formulas:
                [
                    new ReportWriterFormulaDefinitionDto("returnPct", "{pnl} / {marketValue} * 100")
                ])
        };

        var rendered = ReportWriterGridEngine.RenderGrids(grids, rows).Single();

        rendered.Columns.Select(column => column.Key).Should().Equal(
            "sector",
            "US:marketValue",
            "US:pnl",
            "EU:marketValue",
            "EU:pnl",
            "returnPct");
        rendered.Rows.Should().HaveCount(2);
        rendered.Rows.Should().Contain(row =>
            row.Values["sector"] == "Technology" &&
            row.Values["US:marketValue"] == "100" &&
            row.Values["US:pnl"] == "10" &&
            row.Values["EU:marketValue"] == "50" &&
            row.Values["EU:pnl"] == "5" &&
            row.Values["returnPct"] == "10");
        rendered.Rows.Should().Contain(row =>
            row.Values["sector"] == "Rates" &&
            row.Values["US:marketValue"] == "40" &&
            row.Values["US:pnl"] == "-2" &&
            row.Values["EU:marketValue"] == "0" &&
            row.Values["EU:pnl"] == "0" &&
            row.Values["returnPct"] == "-5");
        rendered.Lineage.Should().NotBeNull();
        rendered.Lineage!.SourceFields.Should().Equal("marketValue", "pnl", "region", "sector");
    }

