    [Fact]
    public void RenderGrids_FormulaLineageIncludesTotalAndBareIdentifierReferences()
    {
        var rows = new[]
        {
            Row(("sector", "Technology"), ("marketValue", "100"), ("pnl", "10")),
            Row(("sector", "Credit"), ("marketValue", "50"), ("pnl", "-5"))
        };
        var grids = new[]
        {
            new ReportWriterGridDefinitionDto(
                "formula-lineage",
                "Formula Lineage",
                ReportWriterGridKindDto.Pivot,
                RowFields: ["sector"],
                Metrics:
                [
                    new ReportWriterMetricDefinitionDto("marketValue", "marketValue"),
                    new ReportWriterMetricDefinitionDto("pnl", "pnl")
                ],
                Formulas:
                [
                    new ReportWriterFormulaDefinitionDto("weightPct", "{marketValue} / total(marketValue) * 100"),
                    new ReportWriterFormulaDefinitionDto("bareReturnPct", "pnl / marketValue * 100"),
                    new ReportWriterFormulaDefinitionDto("totalBraceCheck", "{pnl} / total({marketValue}) * 100")
                ])
        };

        var rendered = ReportWriterGridEngine.RenderGrids(grids, rows).Single();

        rendered.Warnings.Should().BeEmpty();
        rendered.Rows.Should().Contain(row =>
            row.Values["sector"] == "Technology" &&
            row.Values["weightPct"] == "66.666667" &&
            row.Values["bareReturnPct"] == "10" &&
            row.Values["totalBraceCheck"] == "6.666667");
        rendered.Lineage.Should().NotBeNull();
        rendered.Lineage!.Formulas.Should().Contain(formula =>
            formula.Name == "weightPct" &&
            formula.SourceFields.SequenceEqual(new[] { "marketValue" }));
        rendered.Lineage.Formulas.Should().Contain(formula =>
            formula.Name == "bareReturnPct" &&
            formula.SourceFields.SequenceEqual(new[] { "marketValue", "pnl" }));
        rendered.Lineage.Formulas.Should().Contain(formula =>
            formula.Name == "totalBraceCheck" &&
            formula.SourceFields.SequenceEqual(new[] { "marketValue", "pnl" }));
        rendered.Lineage.SourceFields.Should().Equal("marketValue", "pnl", "sector");
        rendered.DataDictionary.Should().NotBeNull();
        rendered.DataDictionary!.Should().Contain(field =>
            field.Key == "weightPct" &&
            field.IsGenerated &&
            field.SourceField == "marketValue");
        rendered.DataDictionary.Should().Contain(field =>
            field.Key == "totalBraceCheck" &&
            field.IsGenerated &&
            field.SourceField == "marketValue;pnl");
        rendered.ValidationChecks.Should().NotBeNull();
        rendered.ValidationChecks!.Should().OnlyContain(check => check.Status == "Passed");
    }

    [Fact]
    public void RenderGrids_CustomFormulaFunctionsEvaluateAndRetainSourceLineage()
    {
        var rows = new[]
        {
            Row(("strategy", "Core"), ("marketValue", "100"), ("pnl", "-12"), ("riskLimit", "10")),
            Row(("strategy", "Core"), ("marketValue", "0"), ("pnl", "4"), ("riskLimit", "7")),
            Row(("strategy", "Hedge"), ("marketValue", "50"), ("pnl", "5"), ("riskLimit", "9"))
        };
        var grids = new[]
        {
            new ReportWriterGridDefinitionDto(
                "formula-functions",
                "Formula Functions",
                ReportWriterGridKindDto.Pivot,
                RowFields: ["strategy"],
                Metrics:
                [
                    new ReportWriterMetricDefinitionDto("marketValue", "marketValue"),
                    new ReportWriterMetricDefinitionDto("pnl", "pnl"),
                    new ReportWriterMetricDefinitionDto("riskLimit", "riskLimit")
                ],
                Formulas:
                [
                    new ReportWriterFormulaDefinitionDto("absolutePnl", "abs({pnl})"),
                    new ReportWriterFormulaDefinitionDto("cappedRisk", "min(abs({pnl}), max({riskLimit}, 8))"),
                    new ReportWriterFormulaDefinitionDto("guardedReturn", "safeDivide({pnl}, {marketValue}, -999) * 100")
                ])
        };

        var rendered = ReportWriterGridEngine.RenderGrids(grids, rows).Single();

        rendered.Warnings.Should().BeEmpty();
        rendered.Rows.Should().Contain(row =>
            row.Values["strategy"] == "Core" &&
            row.Values["marketValue"] == "100" &&
            row.Values["pnl"] == "-8" &&
            row.Values["absolutePnl"] == "8" &&
            row.Values["cappedRisk"] == "8" &&
            row.Values["guardedReturn"] == "-8");
        rendered.Rows.Should().Contain(row =>
            row.Values["strategy"] == "Hedge" &&
            row.Values["marketValue"] == "50" &&
            row.Values["pnl"] == "5" &&
            row.Values["absolutePnl"] == "5" &&
            row.Values["cappedRisk"] == "5" &&
            row.Values["guardedReturn"] == "10");
        rendered.Lineage.Should().NotBeNull();
        rendered.Lineage!.Formulas.Should().Contain(formula =>
            formula.Name == "cappedRisk" &&
            formula.SourceFields.SequenceEqual(new[] { "pnl", "riskLimit" }));
        rendered.Lineage.Formulas.Should().Contain(formula =>
            formula.Name == "guardedReturn" &&
            formula.SourceFields.SequenceEqual(new[] { "marketValue", "pnl" }));
        rendered.Lineage.SourceFields.Should().Equal("marketValue", "pnl", "riskLimit", "strategy");
        rendered.DataDictionary.Should().Contain(field =>
            field.Key == "guardedReturn" &&
            field.Role == "formula" &&
            field.SourceField == "marketValue;pnl" &&
            field.IsGenerated);
        rendered.ValidationChecks.Should().NotBeNull();
        rendered.ValidationChecks!.Should().OnlyContain(check => check.Status == "Passed");
    }

