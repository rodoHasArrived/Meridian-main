"""Render lexical C# API declarations without building platform-specific projects.

Uses the schema-control tokenizer to skip strings/comments and balance scopes.
This is deliberately a declaration reference, not a semantic compiler model.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass, field, replace
import html
import os
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

from tools.schema_control import contracts as cs

HEADER = "<!-- Generated by build/scripts/docs/render-public-type-reference.py. Do not edit directly. -->"
EXCLUDE = {".git", "node_modules", "bin", "obj", "__pycache__", ".pytest_cache", ".vs"}
PAGE_SIZE = 50


@dataclass
class Member:
    signature: str
    line: int
    summary: str = ""


@dataclass
class Declaration:
    name: str
    namespace: str
    kind: str
    module: str
    path: str
    line: int
    signature: str
    summary: str
    start: int
    end: int
    body: int | None
    arity: int
    containing: str = ""
    containing_identity: str = ""
    members: list[Member] = field(default_factory=list)

    @property
    def qualified_name(self) -> str:
        names = [part for part in (self.namespace, self.containing, self.name) if part]
        return ".".join(names)

    @property
    def key(self) -> tuple[str, str, int]:
        return self.module, self.namespace + "." + self.containing_identity + "." + self.name, self.arity


def _format(tokens: list) -> str:
    literals = {}
    safe_tokens = []
    for index, token in enumerate(tokens):
        if token.kind == "string":
            marker = f"__MERIDIAN_SOURCE_LITERAL_{index}__"
            literals[marker] = token.text
            safe_tokens.append(replace(token, text=marker))
        else:
            safe_tokens.append(token)
    value = cs._format_tokens(safe_tokens)
    value = re.sub(r"\b(?!(?:public|private|protected|internal|static|readonly|new|return|throw)\b)([A-Za-z_][A-Za-z_0-9]*) \(", r"\1(", value)
    value = re.sub(r"\s*;\s*", "; ", value).rstrip()
    value = re.sub(r"([?>\]])([A-Za-z_])", r"\1 \2", value)
    value = re.sub(r"\](?=\{)", "] ", value)
    value = re.sub(r"=(?=\[)", "= ", value)
    for marker, literal in literals.items():
        value = value.replace(marker, literal)
    return value


def _doc_position(tokens: list, index: int, pairs: dict[int, int]) -> int:
    while index and tokens[index - 1].text == "]" and index - 1 in pairs:
        index = pairs[index - 1]
    return tokens[index].start


def _summary(source: str, position: int) -> str:
    # Declarations call this at the first attribute/declaration token. Walk
    # only adjacent preceding lines: slicing/splitting the entire file prefix
    # per member makes large generated DTO files quadratic.
    cursor = source.rfind("\n", 0, position) + 1
    if source[cursor:position].strip():
        return ""
    docs = []
    while cursor > 0:
        end = cursor - 1
        previous = source.rfind("\n", 0, end) + 1
        stripped = source[previous:end].lstrip()
        if not stripped.strip() and not docs:
            cursor = previous
            continue
        if not stripped.startswith("///"):
            break
        docs.append(stripped[3:])
        cursor = previous
    if not docs:
        return ""
    xml_text = "\n".join(reversed(docs))
    try:
        element = ET.fromstring("<doc>" + xml_text + "</doc>")
        summary = element.find("summary")
        if summary is None:
            return ""
        for child in summary.iter():
            if child.tag in {"see", "seealso"}:
                child.text = child.attrib.get("cref", child.attrib.get("href", child.attrib.get("langword", "")))
            elif child.tag in {"paramref", "typeparamref"}:
                child.text = child.attrib.get("name", "")
        return " ".join("".join(summary.itertext()).split())
    except ET.ParseError:
        # Malformed XML remains visible through the source link; don't guess.
        return ""


def _members(tokens: list, decl: Declaration, pairs: dict[int, int], source: str) -> list[Member]:
    if decl.body is None:
        return []
    start = decl.body + 1
    end = decl.end
    if decl.kind == "enum":
        return [Member(_format(group), group[0].line, _summary(source, group[0].start))
                for group in cs._split_enum_members(tokens[start:end]) if group]
    result = []
    cursor = start
    interface = decl.kind == "interface"
    while cursor < end:
        # Preprocessor directives are not declarations. Their branches are
        # scanned independently, without claiming a selected target framework.
        if tokens[cursor].text == "#":
            line = tokens[cursor].line
            while cursor < end and tokens[cursor].line == line:
                cursor += 1
            continue
        member_start = cursor
        header_end = None
        terminator = None
        scan = cursor
        while scan < end:
            word = tokens[scan].text
            if word in {"(", "["}:
                close = pairs.get(scan)
                if close is None:
                    break
                scan = close + 1
                continue
            if word in {"{", ";", "=>"}:
                header_end, terminator = scan, word
                break
            scan += 1
        if header_end is None:
            break
        header = tokens[member_start:header_end]
        clean, _attrs = cs._strip_attributes(header)
        words = [token.text for token in clean]
        visible = "public" in words or (interface and not any(w in {"private", "protected", "internal"} for w in words))
        nested = any(w in cs._TYPE_KINDS for w in words[:6])
        after = header_end + 1
        signature = _format(header)
        assigned = len(cs._split_top_level(clean, "=")) > 1
        callable_member = any(
            t.text == "(" and n > 0 and (clean[n-1].kind == "identifier" or clean[n-1].text == ">")
            and clean[n-1].text not in {"public", "private", "protected", "internal", "static", "readonly"}
            for n, t in enumerate(clean)
        )
        if terminator == "{":
            close = pairs.get(header_end)
            if close is None:
                break
            body_tokens = tokens[header_end + 1:close]
            # A property/event body has accessor keywords at its own scope;
            # method bodies are never emitted as reference declarations.
            if not assigned and not callable_member:
                accessors = []
                inner = 0
                while inner < len(body_tokens):
                    token = body_tokens[inner]
                    if token.text in {"get", "set", "init", "add", "remove"}:
                        modifier = body_tokens[inner-1].text if inner and body_tokens[inner-1].text in {"private", "protected", "internal"} else ""
                        accessors.append((modifier + " " if modifier else "") + token.text + ";")
                    if token.text in {"{", "("}:
                        absolute = header_end + 1 + inner
                        body_close = pairs.get(absolute)
                        if body_close is not None:
                            inner = body_close - header_end
                            continue
                    inner += 1
                if accessors:
                    signature += " { " + " ".join(accessors) + " }"
                else:
                    signature += ";"
            elif assigned:
                signature = _format(tokens[member_start:close + 1])
            else:
                signature += ";"
            after = close + 1
            if after < end and tokens[after].text == "=":
                initializer = after
                after += 1
                while after < end and tokens[after].text != ";":
                    if tokens[after].text in {"{", "(", "["} and after in pairs:
                        after = pairs[after] + 1
                    else:
                        after += 1
                signature += " " + _format(tokens[initializer:after]) + ";"
                after += 1
            elif after < end and tokens[after].text == ";":
                if not signature.endswith(";"):
                    signature += ";"
                after += 1
        elif terminator == "=>":
            # Omit executable expressions; retain the exact callable/property
            # declaration and its return type, parameters and defaults.
            signature += " => …;"
            while after < end and tokens[after].text != ";":
                if tokens[after].text in {"{", "(", "["} and after in pairs:
                    after = pairs[after] + 1
                else:
                    after += 1
            after += 1
        else:
            signature += ";"
        if visible and not nested and clean:
            result.append(Member(signature, clean[0].line, _summary(source, header[0].start)))
        cursor = max(cursor + 1, after)
    return result


def parse_file(root: Path, path: Path) -> list[Declaration]:
    source = path.read_text(encoding="utf-8-sig")
    tokens = cs._tokenize(source)
    pairs = cs._matching_pairs(tokens)
    namespaces = cs._namespace_ranges(tokens, pairs)
    result = []
    # Every enclosing scope matters for identity, even when the enclosing type
    # itself is internal/private and therefore has no separate public entry.
    scopes = []
    for index, token in enumerate(tokens):
        if index == 0 or token.text not in cs._TYPE_KINDS:
            continue
        if token.text in {"class", "struct"} and tokens[index-1].text == "record":
            continue
        scope = cs._find_type_declaration(tokens, index - 1, pairs)
        if scope is not None:
            scope["start"] = index
            parents = [p for p in scopes if p["body_start"] is not None and p["body_start"] < index < p["end"]]
            parent = min(parents, key=lambda p: p["end"] - p["start"]) if parents else None
            scope["qualified_local"] = ".".join(x for x in ((parent["qualified_local"] if parent else ""), scope["name"]) if x)
            own_identity = scope["name"] + (f"`{len(scope['type_parameters'])}" if scope["type_parameters"] else "")
            scope["identity"] = ".".join(x for x in ((parent["identity"] if parent else ""), own_identity) if x)
            scopes.append(scope)
    relative = path.relative_to(root).as_posix()
    for index, token in enumerate(tokens):
        if token.text != "public":
            continue
        found = cs._find_type_declaration(tokens, index, pairs)
        if found is None:
            continue
        body = found["body_start"]
        header_end = body if body is not None else found["end"]
        signature = _format(tokens[index:header_end])
        item = Declaration(found["name"], cs._namespace_at(index, namespaces), found["kind"],
                           Path(relative).parts[1], relative, token.line, signature,
                           _summary(source, _doc_position(tokens, index, pairs)), index, found["end"], body,
                           len(found["type_parameters"]))
        result.append(item)
    for item in result:
        parents = [p for p in scopes if p["body_start"] is not None and p["body_start"] < item.start < p["end"]]
        if parents:
            parent = min(parents, key=lambda p: p["end"] - p["start"])
            item.containing = parent["qualified_local"]
            item.containing_identity = parent["identity"]
        item.members = _members(tokens, item, pairs, source)
    return result


def collect(root: Path) -> list[Declaration]:
    result = []
    for directory, dirs, files in os.walk(root / "src"):
        dirs[:] = sorted(d for d in dirs if d not in EXCLUDE)
        for name in sorted(files):
            if name.endswith(".cs"):
                result.extend(parse_file(root, Path(directory) / name))
    return sorted(result, key=lambda x: (x.module.casefold(), x.qualified_name.casefold(), x.arity, x.path.casefold(), x.line))


def _code(value: str) -> str:
    # HTML code makes pipes, backticks and generic brackets safe in tables.
    return "<code>" + html.escape(value).replace("\n", " ").replace("|", "&#124;") + "</code>"


def _prose(value: str) -> str:
    return html.escape(value).replace("|", "&#124;").replace("[", "&#91;").replace("]", "&#93;")


def _source(decl: Declaration, line: int | None = None) -> str:
    return f"[{decl.path}:{line or decl.line}](../../../../{decl.path}#L{line or decl.line})"


def render(root: Path, page_size: int = PAGE_SIZE) -> dict[str, str]:
    declarations = collect(root)
    groups: dict[tuple[str, str, int], list[Declaration]] = {}
    for declaration in declarations:
        groups.setdefault(declaration.key, []).append(declaration)
    modules: dict[str, list[list[Declaration]]] = {}
    for items in groups.values():
        modules.setdefault(items[0].module, []).append(items)
    outputs = {}
    index = [HEADER, "", "# Public C# source reference", "",
             "This generated reference describes declarations in `src/`: type signatures, source XML summaries, "
             "record parameters, declared public members, and enum values. It is regenerated from source, "
             "including partial declarations and declarations in conditional branches.", "",
             "It is a lexical reference, not a compiled API or a runtime/evidence claim. It does not resolve "
             "inheritance, conditional compilation, generated members, overload binding, or runtime defaults. "
             "Public nested types retain their containing name; public members of an internal enclosing type "
             "may still appear. Method bodies and expression bodies are omitted. Values shown in declarations "
             "are source initializers/parameter defaults, not a guarantee of effective runtime configuration.", "",
             "## Regeneration", "", "```bash", "python3 build/scripts/docs/render-public-type-reference.py", "python3 build/scripts/docs/render-public-type-reference.py --check", "```", "",
             "## Modules", "", "| Module | Types | Reference pages |", "| --- | ---: | --- |"]
    for module, types in modules.items():
        slug = module.lower()
        page_count = (len(types) + page_size - 1) // page_size
        page_links = []
        for page in range(page_count):
            filename = f"{slug}/page-{page + 1:03d}.md"
            page_links.append(f"[{page+1}]({filename})")
            lines = [HEADER, "", f"# {module} public source reference — {page + 1}/{page_count}", "",
                     "[All modules](../README.md) · [Reference scope and regeneration](../README.md#regeneration)", "",
                     "Each entry retains source-declared members and XML summaries. See the index for lexical scope limitations.", ""]
            # Page is in a module subdirectory; source links account for it.
            for variants in types[page*page_size:(page+1)*page_size]:
                first = variants[0]
                suffix = f" (generic arity {first.arity})" if first.arity else ""
                lines += [f"## {first.name}{suffix}", "", f"Qualified name: {_code(first.qualified_name)}. Kind: `{first.kind.replace('_', ' ')}`.", ""]
                for variant in variants:
                    lines += [f"Source: {_source(variant)}.", ""]
                    if variant.summary:
                        lines += [_prose(variant.summary), ""]
                    fence = "`" * max(3, max((len(run) for run in re.findall(r"`+", variant.signature)), default=0) + 1)
                    lines += [fence + "csharp", variant.signature + (";" if variant.body is None else ""), fence, ""]
                    if variant.members:
                        label = "Enum declarations" if variant.kind == "enum" else "Declared public members"
                        lines += [f"{label}:", "", "| Declaration | Source | Summary |", "| --- | --- | --- |"]
                        for member in variant.members:
                            lines.append(f"| {_code(member.signature)} | {_source(variant, member.line)} | {_prose(member.summary)} |")
                        lines += [""]
            outputs[filename] = "\n".join(lines)
        index.append(f"| `{module}` | {len(types)} | {' · '.join(page_links)} |")
    index += ["", f"Total: **{len(groups)}** distinct module/qualified-name/arity entries from **{len(declarations)}** source declarations.", ""]
    outputs["README.md"] = "\n".join(index)
    return outputs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--check", action="store_true", help="Fail on missing, changed or obsolete generated files without writing.")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    output = root / "docs/reference/source-api"
    expected = render(root)
    actual = {path.relative_to(output).as_posix(): path for path in output.rglob("*.md")} if output.exists() else {}
    stale = [name for name, content in expected.items() if name not in actual or actual[name].read_text(encoding="utf-8") != content]
    obsolete = sorted(set(actual) - set(expected))
    if args.check:
        if stale or obsolete:
            for name in sorted(stale + obsolete):
                print(f"Stale source reference: {name}", file=sys.stderr)
            return 1
    else:
        for name, content in expected.items():
            path = output / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        for name in obsolete:
            path = actual[name]
            if not path.read_text(encoding="utf-8").startswith(HEADER):
                raise ValueError(f"Refusing to remove a non-generated file: {path}")
            path.unlink()
    print(f"Public source reference: {len(expected)} files {'checked' if args.check else 'rendered'}")
    return 0
