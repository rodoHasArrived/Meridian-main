-- Migration 068: Declare the terms family inside every stored asset_specific_terms document.
-- ADR-024 amendment 2026-11-13 (proposed, requires human review), step 3. Migration 042 promoted the
-- family to the terms_format column without touching the payload; untagged rows kept being
-- classified by shape on every read. Every writer now declares termsFormat (amendment steps 1-2),
-- so the remaining untagged population is current state written before the tag existed. This
-- migration rewrites current state only:
--   * it adds termsFormat to securities.asset_specific_terms, copied from terms_format, for flat and
--     customProfile rows. No other member changes: assetClassTermsVersion is never added (an absent
--     version keeps reading as 1), schemaVersion is untouched, and the version column is untouched;
--   * security_events is append-only (migration 059) and is never rewritten; snapshots are
--     regenerated by an application job (SecurityMasterSnapshotRegenerationService), not here.
-- Readers already resolve an untagged row to the family the column records, so a declared tag equal
-- to the column changes no read. SecurityMasterMigrationRunner gates the upgrade (writers locked out
-- with NOWAIT, pre-068 writers retired) before this script runs.
--
-- M1: refuse before writing anything when an untagged row cannot be stamped exactly as readers infer
-- it. The asset-specific-terms slot never declares the economic family on behalf of a legacy row,
-- and a row whose column disagrees with the shape rule (the 042 rule, pinned to
-- SecurityTermsEnvelope.ResolveFormat) or that is not a JSON object needs an explicit repair.
do $$
declare
    economic_count bigint;
    mismatch_count bigint;
    non_object_count bigint;
begin
    select count(*) into non_object_count
    from __SCHEMA__.securities
    where jsonb_typeof(asset_specific_terms) is distinct from 'object';

    if non_object_count > 0 then
        raise exception using
            errcode = '23514',
            message = format(
                'Security Master migration 068 refused: %s securities row(s) hold asset_specific_terms that are not a JSON object, so no termsFormat can be declared.',
                non_object_count),
            hint = 'Repair each such row through a Security Master amend before retrying; nothing was rewritten.';
    end if;

    with untagged as (
        select terms_format,
               case
                   when jsonb_typeof(asset_specific_terms->'customProfileId') = 'string'
                        and jsonb_typeof(asset_specific_terms->'profileFields') = 'object'
                       then 'customProfile'
                   when jsonb_typeof(asset_specific_terms->'schemaVersion') = 'number'
                        and asset_specific_terms->>'schemaVersion' = '2'
                        and asset_specific_terms ?| array[
                            'maturity', 'coupon', 'payment', 'accrual', 'discount',
                            'redemption', 'call', 'auction', 'sweep', 'financing', 'issuer', 'equityBehavior', 'fund', 'structuredProduct']
                       then 'economic'
                   else 'flat'
               end as inferred_format
        from __SCHEMA__.securities
        where jsonb_typeof(asset_specific_terms->'termsFormat') is distinct from 'string'
    )
    select count(*) filter (where terms_format = 'economic' or inferred_format = 'economic'),
           count(*) filter (where terms_format <> 'economic' and inferred_format <> 'economic'
                                  and terms_format <> inferred_format)
    into economic_count, mismatch_count
    from untagged;

    if economic_count > 0 then
        raise exception using
            errcode = '23514',
            message = format(
                'Security Master migration 068 refused: %s untagged securities row(s) classify as the economic terms family.',
                economic_count),
            hint = 'An untagged economic-shaped document is never stamped by the backfill. Re-write each such security through the economic definition path (which declares termsFormat = economic) or a scoped rebuild, then retry; nothing was rewritten.';
    end if;

    if mismatch_count > 0 then
        raise exception using
            errcode = '23514',
            message = format(
                'Security Master migration 068 refused: %s untagged securities row(s) have a terms_format column that differs from the family their payload shape resolves to.',
                mismatch_count),
            hint = 'Re-save each such security so the store re-derives terms_format, then retry; nothing was rewritten.';
    end if;
end $$;

-- M2: declare the family the column records. A non-string termsFormat member (for example null)
-- declares nothing and is replaced. jsonb_set changes only that one key.
update __SCHEMA__.securities
set asset_specific_terms = jsonb_set(asset_specific_terms, '{termsFormat}', to_jsonb(terms_format), true)
where jsonb_typeof(asset_specific_terms) = 'object'
  and jsonb_typeof(asset_specific_terms->'termsFormat') is distinct from 'string'
  and terms_format in ('flat', 'customProfile');

-- M3: verify. No untagged row remains (the ADR-024 decision-5 count, as
-- ISecurityMasterStore.CountUntaggedAssetSpecificTermsAsync measures it) and every declared tag
-- equals the column.
do $$
declare
    untagged_count bigint;
    disagreeing_count bigint;
begin
    select count(*) into untagged_count
    from __SCHEMA__.securities
    where jsonb_typeof(asset_specific_terms) is distinct from 'object'
       or jsonb_typeof(asset_specific_terms->'termsFormat') is distinct from 'string';

    select count(*) into disagreeing_count
    from __SCHEMA__.securities
    where jsonb_typeof(asset_specific_terms->'termsFormat') = 'string'
      and asset_specific_terms->>'termsFormat' is distinct from terms_format;

    if untagged_count > 0 or disagreeing_count > 0 then
        raise exception using
            errcode = '23514',
            message = format(
                'Security Master migration 068 verification failed: %s untagged row(s) and %s row(s) whose termsFormat differs from terms_format remain.',
                untagged_count, disagreeing_count),
            hint = 'The migration rolled back; nothing was rewritten.';
    end if;
end $$;

-- M4: from now on every stored row declares its family, and the declaration equals the column.
-- Added NOT VALID and then validated, so the constraint itself is checked against every row.
do $$
begin
    alter table __SCHEMA__.securities
        add constraint ck_securities_terms_format_declared
        check (coalesce(asset_specific_terms->>'termsFormat' = terms_format, false)) not valid;
exception
    when duplicate_object then null;
end $$;

alter table __SCHEMA__.securities validate constraint ck_securities_terms_format_declared;

comment on constraint ck_securities_terms_format_declared on __SCHEMA__.securities is
    'Every asset_specific_terms document declares termsFormat, equal to terms_format (ADR-024 amendment 2026-11-13, migration 068).';
