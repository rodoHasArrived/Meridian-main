namespace Meridian.Execution.Sdk;

/// <summary>
/// Who or what originated an order command. Set by server-side callers through the
/// <see cref="OrderSubmissionAuthority"/> factories; never read from client-supplied metadata.
/// </summary>
/// <remarks>
/// See <c>docs/engineering/blueprints/governed-order-command-boundary-blueprint.md</c>. The OMS
/// does not yet consume these types (Phase 2 adds the authority resolver).
/// </remarks>
public enum OrderCommandOrigin
{
    /// <summary>Legacy <see cref="IOrderManager.PlaceOrderAsync"/> calls that carry no typed authority.</summary>
    Unattributed,

    /// <summary>A manual order ticket submitted by an authenticated operator.</summary>
    OperatorTicket,

    /// <summary>A close or upsize action an operator took on an existing position.</summary>
    PositionAction,

    /// <summary>A risk-escalated order released by an approver; carries the parked authority.</summary>
    EscalationRelease,

    /// <summary>An order generated by a running strategy (paper or live run).</summary>
    StrategyRun,

    /// <summary>A kill-switch cancellation. Cancel-only; never refused on authority.</summary>
    KillSwitch
}

/// <summary>Well-known values for <see cref="ExecutionAccountGrant.Source"/>.</summary>
public static class ExecutionAccountGrantSources
{
    /// <summary>Resolved from the authenticated HTTP principal's account-scoped access.</summary>
    public const string HttpPrincipal = "http-principal";

    /// <summary>Derived from a strategy run's retained fund account.</summary>
    public const string StrategyRun = "strategy-run";
}

/// <summary>
/// Proof, resolved at the edge where the principal is known, that an actor may route orders for
/// one fund account. The OMS verifies that the grant is present, names the order's account, and
/// is fresh enough; it does not resolve identity itself.
/// </summary>
public sealed class ExecutionAccountGrant
{
    public ExecutionAccountGrant(Guid fundAccountId, string grantedTo, string source, DateTimeOffset resolvedAt)
    {
        if (fundAccountId == Guid.Empty)
            throw new ArgumentException("An execution account grant must name a fund account.", nameof(fundAccountId));
        ArgumentException.ThrowIfNullOrWhiteSpace(grantedTo);
        ArgumentException.ThrowIfNullOrWhiteSpace(source);

        FundAccountId = fundAccountId;
        GrantedTo = grantedTo.Trim();
        Source = source.Trim();
        ResolvedAt = resolvedAt;
    }

    /// <summary>The fund account the grant covers.</summary>
    public Guid FundAccountId { get; }

    /// <summary>The actor the grant was resolved for.</summary>
    public string GrantedTo { get; }

    /// <summary>How the grant was resolved; see <see cref="ExecutionAccountGrantSources"/>.</summary>
    public string Source { get; }

    /// <summary>When the grant was resolved. The OMS bounds its age at dispatch.</summary>
    public DateTimeOffset ResolvedAt { get; }
}

/// <summary>
/// Typed authority for one order command. Instances are created only through the static
/// factories, which validate the fields each origin requires. There is no public constructor and
/// no JSON constructor, so an HTTP model binder can never produce one from a request body.
/// </summary>
public sealed class OrderSubmissionAuthority
{
    private OrderSubmissionAuthority(
        OrderCommandOrigin origin,
        string actor,
        ExecutionAccountGrant? accountGrant,
        string? runId,
        string? strategyArtifactId,
        string correlationId,
        string? sessionId,
        OrderSubmissionAuthority? releasedFrom)
    {
        Origin = origin;
        Actor = actor;
        AccountGrant = accountGrant;
        RunId = runId;
        StrategyArtifactId = strategyArtifactId;
        CorrelationId = correlationId;
        SessionId = sessionId;
        ReleasedFrom = releasedFrom;
    }

    /// <summary>Who or what originated the command.</summary>
    public OrderCommandOrigin Origin { get; }

    /// <summary>The actor issuing this command. For a release, the approver.</summary>
    public string Actor { get; }

    /// <summary>Account authority. Null only for <see cref="OrderCommandOrigin.KillSwitch"/>.</summary>
    public ExecutionAccountGrant? AccountGrant { get; }

    /// <summary>The strategy run the order belongs to. Set only for strategy-run authority.</summary>
    public string? RunId { get; }

    /// <summary>The strategy artifact the run executes, when the run carries one.</summary>
    public string? StrategyArtifactId { get; }

    /// <summary>Correlates the command with its journal, audit, and operator action.</summary>
    public string CorrelationId { get; }

    /// <summary>The paper session the order belongs to, when a server-side caller assigned one.</summary>
    public string? SessionId { get; }

    /// <summary>For <see cref="OrderCommandOrigin.EscalationRelease"/>, the authority the order was parked with.</summary>
    public OrderSubmissionAuthority? ReleasedFrom { get; }

    /// <summary>Authority for a manual ticket from an authenticated operator.</summary>
    public static OrderSubmissionAuthority ForOperatorTicket(
        string actor,
        ExecutionAccountGrant accountGrant,
        string correlationId,
        string? sessionId = null)
    {
        var normalizedActor = RequireText(actor, nameof(actor));
        RequireGrantFor(accountGrant, normalizedActor, nameof(accountGrant));
        return new OrderSubmissionAuthority(
            OrderCommandOrigin.OperatorTicket,
            normalizedActor,
            accountGrant,
            runId: null,
            strategyArtifactId: null,
            RequireText(correlationId, nameof(correlationId)),
            NormalizeOptional(sessionId),
            releasedFrom: null);
    }

    /// <summary>Authority for a close or upsize action on an existing position.</summary>
    public static OrderSubmissionAuthority ForPositionAction(
        string actor,
        ExecutionAccountGrant accountGrant,
        string correlationId)
    {
        var normalizedActor = RequireText(actor, nameof(actor));
        RequireGrantFor(accountGrant, normalizedActor, nameof(accountGrant));
        return new OrderSubmissionAuthority(
            OrderCommandOrigin.PositionAction,
            normalizedActor,
            accountGrant,
            runId: null,
            strategyArtifactId: null,
            RequireText(correlationId, nameof(correlationId)),
            sessionId: null,
            releasedFrom: null);
    }

    /// <summary>
    /// Authority for an order generated by a strategy run. The correlation id is the run id,
    /// matching what <c>LiveStrategyRunSession</c> stamps today.
    /// </summary>
    public static OrderSubmissionAuthority ForStrategyRun(
        string actor,
        ExecutionAccountGrant accountGrant,
        string runId,
        string? strategyArtifactId = null)
    {
        ArgumentNullException.ThrowIfNull(accountGrant);
        var normalizedRunId = RequireText(runId, nameof(runId));
        return new OrderSubmissionAuthority(
            OrderCommandOrigin.StrategyRun,
            RequireText(actor, nameof(actor)),
            accountGrant,
            normalizedRunId,
            NormalizeOptional(strategyArtifactId),
            normalizedRunId,
            sessionId: null,
            releasedFrom: null);
    }

    /// <summary>
    /// Authority for releasing a risk-escalated order. The parked authority is carried unchanged,
    /// so the OMS rechecks the original account grant and run binding rather than re-deriving them
    /// from the approver.
    /// </summary>
    public static OrderSubmissionAuthority ForEscalationRelease(OrderSubmissionAuthority parked, string approver)
    {
        ArgumentNullException.ThrowIfNull(parked);
        if (parked.Origin == OrderCommandOrigin.KillSwitch)
            throw new ArgumentException("Kill-switch cancellations are never parked for approval.", nameof(parked));

        return new OrderSubmissionAuthority(
            OrderCommandOrigin.EscalationRelease,
            RequireText(approver, nameof(approver)),
            parked.AccountGrant,
            parked.RunId,
            parked.StrategyArtifactId,
            parked.CorrelationId,
            parked.SessionId,
            parked);
    }

    /// <summary>Authority for a kill-switch cancellation. Recorded, never used to refuse a cancel.</summary>
    public static OrderSubmissionAuthority ForKillSwitch(string actor, string correlationId) =>
        new(
            OrderCommandOrigin.KillSwitch,
            RequireText(actor, nameof(actor)),
            accountGrant: null,
            runId: null,
            strategyArtifactId: null,
            RequireText(correlationId, nameof(correlationId)),
            sessionId: null,
            releasedFrom: null);

    /// <summary>
    /// Authority for a legacy <see cref="IOrderManager.PlaceOrderAsync"/> call. Identity is copied
    /// from the request metadata the caller supplied, exactly as the OMS reads it today, and the
    /// origin records that none of it was established by a typed authority. Phase 2 refuses this
    /// origin in Live mode.
    /// </summary>
    public static OrderSubmissionAuthority Unattributed(IReadOnlyDictionary<string, string>? legacyMetadata)
    {
        var actor = ReadMetadata(legacyMetadata, "actor");
        var runId = ReadMetadata(legacyMetadata, "runId");
        var correlationId = ReadMetadata(legacyMetadata, "correlationId");
        return new OrderSubmissionAuthority(
            OrderCommandOrigin.Unattributed,
            actor ?? "unattributed",
            accountGrant: null,
            runId,
            strategyArtifactId: null,
            correlationId ?? runId ?? string.Empty,
            ReadMetadata(legacyMetadata, "sessionId"),
            releasedFrom: null);
    }

    private static string RequireText(string? value, string parameterName)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(value, parameterName);
        return value.Trim();
    }

    private static string? NormalizeOptional(string? value) =>
        string.IsNullOrWhiteSpace(value) ? null : value.Trim();

    private static void RequireGrantFor(ExecutionAccountGrant? grant, string actor, string parameterName)
    {
        ArgumentNullException.ThrowIfNull(grant, parameterName);
        if (!string.Equals(grant.GrantedTo, actor, StringComparison.Ordinal))
            throw new ArgumentException(
                $"The account grant was resolved for '{grant.GrantedTo}', not for the submitting actor '{actor}'.",
                parameterName);
    }

    private static string? ReadMetadata(IReadOnlyDictionary<string, string>? metadata, string key)
    {
        if (metadata is null)
            return null;

        // Request bags deserialized from JSON use a case-sensitive comparer while the OMS reads
        // through ordinal-ignore-case copies; match its reading here.
        foreach (var (candidate, value) in metadata)
        {
            if (string.Equals(candidate, key, StringComparison.OrdinalIgnoreCase))
                return NormalizeOptional(value);
        }

        return null;
    }
}

/// <summary>A new-order command: the order and the typed authority it is submitted under.</summary>
public sealed class OrderSubmitCommand
{
    public OrderSubmitCommand(OrderRequest order, OrderSubmissionAuthority authority)
    {
        Order = order ?? throw new ArgumentNullException(nameof(order));
        Authority = authority ?? throw new ArgumentNullException(nameof(authority));
    }

    public OrderRequest Order { get; }

    public OrderSubmissionAuthority Authority { get; }
}

/// <summary>A cancel command for one working order.</summary>
public sealed class OrderCancelCommand
{
    public OrderCancelCommand(string orderId, OrderSubmissionAuthority authority)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(orderId);
        OrderId = orderId;
        Authority = authority ?? throw new ArgumentNullException(nameof(authority));
    }

    public string OrderId { get; }

    public OrderSubmissionAuthority Authority { get; }
}

/// <summary>A cancel/replace command for one working order.</summary>
public sealed class OrderReplaceCommand
{
    public OrderReplaceCommand(string orderId, OrderModification modification, OrderSubmissionAuthority authority)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(orderId);
        OrderId = orderId;
        Modification = modification ?? throw new ArgumentNullException(nameof(modification));
        Authority = authority ?? throw new ArgumentNullException(nameof(authority));
    }

    public string OrderId { get; }

    public OrderModification Modification { get; }

    public OrderSubmissionAuthority Authority { get; }
}

