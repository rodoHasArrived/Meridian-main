public sealed record AuthorityDecisionSummary(
    OrderCommandOrigin Origin,
    bool IsAuthorized,
    string? ReasonCode,
    string? Reason,
    string Checkpoint,
    string? ReadinessSnapshotVersion,
    string? PromotionAuditReference);
