#!/usr/bin/env python3
"""Convert the design-system TTF fonts to WOFF2 for the browser workstation.

Called by ``scripts/sync-design-system-assets.mjs --write`` when a package font changes; it can
also be run directly. Every ``*.ttf`` in ``--source-dir`` is written to ``--target-dir`` as WOFF2
and recorded in ``woff2-sources.json`` with the SHA-256 of the source TTF and of the WOFF2 output.
Timestamps are not recalculated, so reruns on the same input are byte-identical.

Requires ``fonttools`` and ``brotli``: ``python -m pip install fonttools brotli``.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source-dir", required=True, type=Path)
    parser.add_argument("--target-dir", required=True, type=Path)
    args = parser.parse_args()
    try:
        from fontTools.ttLib import TTFont
    except ImportError:
        print("fonttools is required: python -m pip install fonttools brotli", file=sys.stderr)
        return 2

    sources = sorted(args.source_dir.glob("*.ttf"))
    if not sources:
        print(f"No .ttf fonts in {args.source_dir}", file=sys.stderr)
        return 1
    args.target_dir.mkdir(parents=True, exist_ok=True)
    records = {}
    for source in sources:
        target = args.target_dir / f"{source.stem}.woff2"
        font = TTFont(source, recalcTimestamp=False)
        font.flavor = "woff2"
        font.save(target)
        records[target.name] = {
            "source": f"assets/fonts/{source.name}",
            "sourceSha256": sha256(source),
            "woff2Sha256": sha256(target),
        }
    (args.target_dir / "woff2-sources.json").write_text(json.dumps({
        "$comment": "Generated by scripts/convert-fonts-to-woff2.py via npm run design-system:sync; do not edit.",
        "fonts": records,
    }, indent=2) + "\n", encoding="utf-8")
    print(f"Converted {len(records)} fonts to WOFF2 in {args.target_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
