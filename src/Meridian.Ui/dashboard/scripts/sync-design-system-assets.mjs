#!/usr/bin/env node
/** Project the canonical design-system assets into the native Vite application.
 * No runtime prototype bundle, remote font service, or second React is loaded.
 *
 * Brand, icon and license files are copied byte-for-byte. Package TTF fonts are served as WOFF2:
 * `tokens/fonts.css` is projected with its `.ttf`/`truetype` sources rewritten to `.woff2`/`woff2`,
 * and each WOFF2 is checked against `src/assets/fonts/woff2-sources.json`, which records the SHA-256
 * of its package TTF and of the converted file. Check mode is pure Node; write mode runs
 * `scripts/convert-fonts-to-woff2.py` (fonttools + brotli) only when a package font changed.
 */
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { readFileSync, readdirSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const defaultDashboardRoot = resolve(dirname(scriptPath), "..");

export const FONT_TARGET_DIRECTORY = "src/assets/fonts";
export const FONT_PROVENANCE_FILE = "woff2-sources.json";
const GENERATED_FONT_CSS_HEADER = "/* Generated by scripts/sync-design-system-assets.mjs from the package tokens/fonts.css:\n   TTF sources are served as WOFF2 (provenance in src/assets/fonts/woff2-sources.json). Do not edit. */\n";

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

/** Rewrite package font-face sources from TTF to the WOFF2 copies the dashboard ships. */
export function projectFontCss(packageFontCss) {
  const rewritten = packageFontCss.replace(
    /(assets\/fonts\/[^"')]+)\.ttf(["']?\))(\s*)format\((["'])truetype\4\)/g,
    (_match, stem, close, space, quote) => `${stem}.woff2${close}${space}format(${quote}woff2${quote})`);
  if (/\.ttf\b|truetype/.test(rewritten)) {
    throw new Error("tokens/fonts.css has a TTF source the WOFF2 projection does not recognise; update projectFontCss.");
  }
  return GENERATED_FONT_CSS_HEADER + rewritten;
}

/** Default converter: the deterministic fonttools script next to this file. */
function convertFontsWithPython({ sourceDirectory, targetDirectory }) {
  const converter = join(dirname(scriptPath), "convert-fonts-to-woff2.py");
  const candidates = [process.env.MERIDIAN_PYTHON, "python3", "python"].filter(Boolean);
  for (const python of candidates) {
    const result = spawnSync(python, ["-I", converter, "--source-dir", sourceDirectory, "--target-dir", targetDirectory], { encoding: "utf8" });
    if (result.error?.code === "ENOENT") continue;
    if (result.status === 0) return;
    throw new Error(`WOFF2 conversion failed (${python}):\n${result.stderr || result.stdout}\nInstall the converter dependencies with: ${python} -m pip install fonttools brotli`);
  }
  throw new Error("WOFF2 conversion needs Python 3 with fonttools and brotli (set MERIDIAN_PYTHON to choose an interpreter).");
}

function readProvenance(path) {
  if (!existsSync(path)) return {};
  return JSON.parse(readFileSync(path, "utf8")).fonts ?? {};
}

/** Font files whose WOFF2 copy is missing, stale, or not derived from the current package TTF. */
function fontDrift({ packageFontDirectory, dashboardFontDirectory, ttfNames, dashboardRoot }) {
  const provenance = readProvenance(join(dashboardFontDirectory, FONT_PROVENANCE_FILE));
  const drift = [];
  const expected = new Set();
  for (const ttf of ttfNames) {
    const woff2 = ttf.replace(/\.ttf$/, ".woff2");
    expected.add(woff2);
    const destination = join(dashboardFontDirectory, woff2);
    const record = provenance[woff2];
    const current = record
      && record.source === `assets/fonts/${ttf}`
      && record.sourceSha256 === sha256(readFileSync(join(packageFontDirectory, ttf)))
      && existsSync(destination)
      && record.woff2Sha256 === sha256(readFileSync(destination));
    if (!current) drift.push(relative(dashboardRoot, destination));
  }
  for (const recorded of Object.keys(provenance)) {
    if (!expected.has(recorded)) drift.push(`${relative(dashboardRoot, join(dashboardFontDirectory, FONT_PROVENANCE_FILE))} (${recorded} has no package source)`);
  }
  const stale = existsSync(dashboardFontDirectory)
    ? readdirSync(dashboardFontDirectory).filter((name) => /\.(ttf|otf|woff)$/i.test(name))
    : [];
  for (const name of stale) drift.push(`${relative(dashboardRoot, join(dashboardFontDirectory, name))} (only WOFF2 is shipped)`);
  return { drift, stale };
}

export function synchronizeDesignSystemAssets({
  dashboardRoot = defaultDashboardRoot,
  packageRoot = resolve(dashboardRoot, "../../../Meridian Design System"),
  write = false,
  convertFonts = convertFontsWithPython,
} = {}) {
  const version = JSON.parse(readFileSync(join(packageRoot, "release.json"), "utf8")).version;
  const bridgePath = join(dashboardRoot, "src/design-system/assets.ts");
  const bridge = readFileSync(bridgePath, "utf8");
  if (!bridge.includes(`DESIGN_SYSTEM_VERSION = "${version}"`)) {
    throw new Error(`Dashboard asset bridge must declare canonical design-system version ${version}`);
  }
  const packageFontDirectory = join(packageRoot, "assets", "fonts");
  const dashboardFontDirectory = join(dashboardRoot, FONT_TARGET_DIRECTORY);
  const copies = [];
  const ttfNames = [];
  for (const group of ["brand", "icons", "fonts"]) {
    const sourceDirectory = join(packageRoot, "assets", group);
    for (const entry of readdirSync(sourceDirectory, { withFileTypes: true }).sort((a, b) => a.name < b.name ? -1 : 1)) {
      if (!entry.isFile()) throw new Error(`Only regular canonical assets are supported: ${join(sourceDirectory, entry.name)}`);
      if (group === "fonts" && /\.ttf$/i.test(entry.name)) { ttfNames.push(entry.name); continue; }
      const destination = group === "fonts" && entry.name.startsWith("OFL-")
        ? join(dashboardRoot, "public/licenses", entry.name)
        : join(dashboardRoot, "src/assets", group, entry.name);
      copies.push([readFileSync(join(sourceDirectory, entry.name)), destination]);
    }
  }
  copies.push([
    Buffer.from(projectFontCss(readFileSync(join(packageRoot, "tokens/fonts.css"), "utf8"))),
    join(dashboardRoot, "src/design-system/fonts.css"),
  ]);

  const drift = [];
  for (const [canonical, destination] of copies) {
    if (existsSync(destination) && readFileSync(destination).equals(canonical)) continue;
    drift.push(relative(dashboardRoot, destination));
    if (write) {
      mkdirSync(dirname(destination), { recursive: true });
      writeFileSync(destination, canonical);
    }
  }

  const fonts = fontDrift({ packageFontDirectory, dashboardFontDirectory, ttfNames, dashboardRoot });
  drift.push(...fonts.drift);
  if (write && fonts.drift.length) {
    for (const name of fonts.stale) rmSync(join(dashboardFontDirectory, name));
    mkdirSync(dashboardFontDirectory, { recursive: true });
    convertFonts({ sourceDirectory: packageFontDirectory, targetDirectory: dashboardFontDirectory });
    const remaining = fontDrift({ packageFontDirectory, dashboardFontDirectory, ttfNames, dashboardRoot }).drift;
    if (remaining.length) throw new Error(`WOFF2 conversion left font drift:\n${remaining.join("\n")}`);
  }

  if (drift.length && !write) throw new Error(`Design-system ${version} asset drift:\n${drift.join("\n")}\nRun npm run design-system:sync.`);
  return { version, files: copies.length + ttfNames.length, updated: write ? drift : [] };
}

if (process.argv[1] && resolve(process.argv[1]) === scriptPath) {
  const args = process.argv.slice(2);
  if (args.some(arg => !["--write", "--check"].includes(arg)) || args.includes("--write") && args.includes("--check")) {
    throw new Error("Usage: node scripts/sync-design-system-assets.mjs [--check | --write]");
  }
  const result = synchronizeDesignSystemAssets({ write: args.includes("--write") });
  console.log(`Design-system ${result.version}: ${result.files} production asset/font/license files ${args.includes("--write") ? `synchronized (${result.updated.length} updated)` : "match canonical source"}.`);
}
