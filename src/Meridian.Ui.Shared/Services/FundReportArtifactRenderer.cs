    internal static byte[] BuildTrialBalanceCsv(IReadOnlyList<EnrichedLedgerRow> rows, CancellationToken ct)
    {
        var builder = new StringBuilder();
        AppendCsvRow(builder, TrialBalanceHeaders);
        foreach (var row in OrderTrialBalanceRows(rows))
        {
            ct.ThrowIfCancellationRequested();
            AppendCsvRow(builder, MapTrialBalanceWorkbookRow(row));
        }

        return Encoding.UTF8.GetBytes(builder.ToString());
    }

    internal static byte[] BuildAssetClassSectionsCsv(IReadOnlyList<AssetClassSection> sections, CancellationToken ct)
    {
        var builder = new StringBuilder();
        AppendCsvRow(builder, AssetClassHeaders);
        foreach (var section in OrderAssetClassSections(sections))
        {
            ct.ThrowIfCancellationRequested();
            AppendCsvRow(builder,
            [
                section.AssetClass,
                section.Total,
                section.Rows.Count
            ]);
        }

        return Encoding.UTF8.GetBytes(builder.ToString());
    }

    internal static void AppendCsvRow(StringBuilder builder, IEnumerable<object?> values)
    {
        var first = true;
        foreach (var value in values)
        {
            if (!first)
            {
                builder.Append(',');
            }

            builder.Append(EscapeCsvValue(value));
            first = false;
        }

        builder.AppendLine();
    }

    internal static string EscapeCsvValue(object? value)
    {
        var text = value switch
        {
            null => string.Empty,
            IFormattable formattable => formattable.ToString(format: null, CultureInfo.InvariantCulture),
            _ => value.ToString() ?? string.Empty
        };

        if (IsPotentialSpreadsheetFormula(text))
        {
            text = $"'{text}";
        }

        return text.IndexOfAny(['"', ',', '\r', '\n']) < 0
            ? text
            : $"\"{text.Replace("\"", "\"\"", StringComparison.Ordinal)}\"";
    }

    internal static bool IsPotentialSpreadsheetFormula(string text)
    {
        if (string.IsNullOrEmpty(text))
        {
            return false;
        }

        return text[0] is '=' or '+' or '-' or '@' or '\t' or '\r';
    }

    internal static string? FormatStructuredGuid(Guid? value) =>
        value?.ToString("D");

    internal static string? FormatExternalGlDimensions(LedgerDimensionSetDto? dimensions)
    {
        if (dimensions?.ExternalGlDimensions is not { Count: > 0 } externalGlDimensions)
        {
            return null;
        }

        var ordered = new SortedDictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var (key, value) in externalGlDimensions)
        {
            ordered[key] = value;
        }

        return JsonSerializer.Serialize(ordered);
    }
